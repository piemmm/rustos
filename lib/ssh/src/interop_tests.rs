fn keys(cipher: Cipher, mac: Option<Mac>, material: &Material) -> Keys {
    Keys::new(cipher, mac, material.key, material.iv, material.integrity).expect("as derived")
}

fn client_padding() -> [u8; 64] {
    core::array::from_fn(|at| 0xA5 ^ u8::try_from(at).expect("small"))
}

/// `SSH_MSG_SERVICE_REQUEST` or `SSH_MSG_SERVICE_ACCEPT` for `ssh-userauth`.
fn service(message: u8) -> Vec<u8> {
    let mut out = Vec::new();
    let mut writer = Writer::new(&mut out);
    writer.byte(message);
    writer.string(b"ssh-userauth");
    writer.finish().expect("small");
    out
}

/// The fixture client's `SSH_MSG_KEXINIT`, offering exactly `cipher`.
fn client_kexinit(cipher: Cipher) -> Vec<u8> {
    let mut out = Vec::new();
    let mut writer = Writer::new(&mut out);
    writer.byte(msg::KEXINIT);
    writer.fixed(&core::array::from_fn::<u8, 16, _>(|at| {
        u8::try_from(at).expect("small")
    }));
    for list in [
        "curve25519-sha256,ext-info-c,kex-strict-c-v00@openssh.com",
        "ssh-ed25519",
        cipher.name(),
        cipher.name(),
        "hmac-sha2-256",
        "hmac-sha2-256",
        "none",
        "none",
        "",
        "",
    ] {
        writer.name_list(NameList::new(list).expect("valid names"));
    }
    writer.boolean(false);
    writer.uint32(0);
    writer.finish().expect("small");
    out
}

#[test]
fn every_forced_cipher_opens_what_openssh_sent_and_seals_what_it_accepted() {
    for session in &SESSIONS {
        let (cipher, mac) = (session.cipher, session.mac);
        let mut opener = Opener::new();
        opener.rekey(&keys(cipher, mac, &session.server), true, None);
        let mut ext_info = session.ext_info.to_vec();
        let Ok(Opened::Packet {
            framed,
            payload,
            sequence,
        }) = opener.open(&mut ext_info)
        else {
            panic!("{cipher:?} {mac:?}: OpenSSH's EXT_INFO did not open");
        };
        assert_eq!((framed, sequence), (session.ext_info.len(), 0));
        assert_eq!(ext_info[payload], EXT_INFO, "{cipher:?} {mac:?}");
        let mut accept = session.accept.to_vec();
        let Ok(Opened::Packet {
            payload, sequence, ..
        }) = opener.open(&mut accept)
        else {
            panic!("{cipher:?} {mac:?}: OpenSSH's SERVICE_ACCEPT did not open");
        };
        assert_eq!(sequence, 1);
        assert_eq!(accept[payload], service(msg::SERVICE_ACCEPT)[..]);

        // OpenSSH chose the same padding this engine would have.
        let mut server = Sealer::new();
        server.rekey(&keys(cipher, mac, &session.server), true, None);
        assert_eq!(
            server.framing(EXT_INFO.len()).expect("fits").total,
            session.ext_info.len()
        );

        let mut client = Sealer::new();
        client.rekey(&keys(cipher, mac, &session.client), true, None);
        let request = service(msg::SERVICE_REQUEST);
        let framing = client.framing(request.len()).expect("fits");
        let mut frame = vec![0u8; framing.total];
        frame[framing.payload_range()].copy_from_slice(&request);
        frame[framing.padding_range()].copy_from_slice(&client_padding()[..framing.padding]);
        client.seal(&mut frame, &framing).expect("seals");
        assert_eq!(frame, session.request, "{cipher:?} {mac:?}");
    }
}

#[test]
fn openssh_plaintext_framing_is_reproduced_byte_for_byte() {
    let packet = &CHACHA_SERVER_BYTES[SERVER_KEXINIT];
    let mut received = packet.to_vec();
    let Ok(Opened::Packet {
        framed, payload, ..
    }) = Opener::new().open(&mut received)
    else {
        panic!("OpenSSH's KEXINIT did not open");
    };
    assert_eq!(framed, packet.len());
    let payload = received[payload].to_vec();
    assert_eq!(payload[0], msg::KEXINIT);
    let mut sealer = Sealer::new();
    let framing = sealer.framing(payload.len()).expect("fits");
    let mut frame = vec![0xEEu8; framing.total];
    frame[framing.payload_range()].copy_from_slice(&payload);
    frame[framing.padding_range()].fill(0);
    sealer.seal(&mut frame, &framing).expect("seals");
    assert_eq!(frame, packet);
    assert_eq!(frame[LENGTH_LEN], 7, "OpenSSH's own padding length");
}

/// What the client transport handed up, owned so the test can act on it.
#[derive(Debug)]
enum Event {
    Message { sequence: u32, payload: Vec<u8> },
    NewKeys,
}

fn pull(transport: &mut Transport) -> Option<Event> {
    match transport
        .next_received()
        .expect("OpenSSH's bytes are genuine")?
    {
        Received::Message { sequence, payload } => Some(Event::Message {
            sequence,
            payload: payload.to_vec(),
        }),
        Received::NewKeys => Some(Event::NewKeys),
        other => panic!("OpenSSH sent nothing else: {other:?}"),
    }
}

/// Replay the `chacha20-poly1305` session through a client transport, feeding
/// the server's bytes `chunk` at a time, and return everything it sent.
fn replay(chunk: usize) -> Vec<u8> {
    let cipher = Cipher::ChaCha20Poly1305;
    let client_keys = Material {
        key: &CHACHA_KEY_C2S,
        iv: &[],
        integrity: &[],
    };
    let server_keys = Material {
        key: &CHACHA_KEY_S2C,
        iv: &[],
        integrity: &[],
    };
    let ident = Ident::new("TAIRiXFixture_1.0", None).expect("valid");
    let mut client = Transport::new(Role::Client, ident).expect("room");
    let kexinit = client_kexinit(cipher);
    client
        .send(msg::KEXINIT, &[&kexinit[1..]])
        .expect("the first message");
    let q_c_len = u32::try_from(Q_C.len()).expect("small").to_be_bytes();
    let mut step = 0;
    for piece in CHACHA_SERVER_BYTES.chunks(chunk) {
        let mut rest = piece;
        while !rest.is_empty() {
            let taken = client.receive(rest).expect("open");
            rest = &rest[taken..];
            while let Some(event) = pull(&mut client) {
                match (step, event) {
                    (
                        0,
                        Event::Message {
                            sequence: 0,
                            payload,
                        },
                    ) if payload[0] == msg::KEXINIT => {
                        client.set_strict(true).expect("KEXINIT came first");
                        client
                            .send(30, &[&q_c_len, &Q_C])
                            .expect("inside the exchange");
                    }
                    (
                        1,
                        Event::Message {
                            sequence: 1,
                            payload,
                        },
                    ) if payload[0] == 31 => {
                        client
                            .install_keys(
                                keys(cipher, None, &client_keys),
                                keys(cipher, None, &server_keys),
                            )
                            .expect("both KEXINITs exchanged");
                    }
                    (2, Event::NewKeys) => client.send_newkeys().expect("keys installed"),
                    (
                        3,
                        Event::Message {
                            sequence: 0,
                            payload,
                        },
                    ) => {
                        assert_eq!(payload, EXT_INFO, "strict KEX restarts the numbering");
                        client.supply_padding(&client_padding()).expect("open");
                        client.supply_padding(&[0x5A; 256]).expect("open");
                        let request = service(msg::SERVICE_REQUEST);
                        client
                            .send(msg::SERVICE_REQUEST, &[&request[1..]])
                            .expect("keys in place and padding supplied");
                    }
                    (
                        4,
                        Event::Message {
                            sequence: 1,
                            payload,
                        },
                    ) => {
                        assert_eq!(payload, service(msg::SERVICE_ACCEPT));
                    }
                    (step, event) => panic!("step {step}: {event:?}"),
                }
                step += 1;
            }
        }
    }
    assert_eq!(step, 5, "the whole exchange was seen");
    assert_eq!(client.peer_ident().map(Ident::as_bytes), Some(SERVER_IDENT));
    client.pending_output().to_vec()
}

#[test]
fn the_transport_reproduces_a_whole_exchange_openssh_accepted() {
    for chunk in [1, 7, 64, 1000, CHACHA_SERVER_BYTES.len()] {
        assert_eq!(
            replay(chunk),
            CHACHA_CLIENT_BYTES,
            "server bytes {chunk} at a time"
        );
    }
}
