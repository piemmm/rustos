#[test]
fn key_generation_matches_the_nist_vector() {
    let key = MlKem768SecretKey::from_seed(&KEYGEN_SEED);
    assert_eq!(sha256(&key.encapsulation_key()), KEYGEN_EK_DIGEST);
}

#[test]
fn encapsulation_matches_the_nist_vector() {
    let (ciphertext, shared) = mlkem768_encapsulate(&ENCAPS_EK, &ENCAPS_M).expect("valid key");
    assert_eq!(sha256(&ciphertext), ENCAPS_CIPHERTEXT_DIGEST);
    assert_eq!(shared, ENCAPS_SHARED_KEY);
}

/// The seed is the whole private key, so a key rebuilt from it decapsulates
/// what was encapsulated to the first one.
#[test]
fn encapsulate_then_decapsulate_round_trips() {
    let key = MlKem768SecretKey::from_seed(&KEYGEN_SEED);
    let (ciphertext, sent) =
        mlkem768_encapsulate(&key.encapsulation_key(), &ENCAPS_M).expect("our own key is valid");
    assert_eq!(key.decapsulate(&ciphertext), sent);

    let reloaded = MlKem768SecretKey::from_seed(&KEYGEN_SEED);
    assert_eq!(reloaded.decapsulate(&ciphertext), sent);
}

/// Encapsulation is a deterministic function of the key and `m`, which is
/// what lets the caller own the randomness — and what makes reusing `m`
/// against one key a repeat rather than a fresh secret.
#[test]
fn encapsulation_is_deterministic_in_its_randomness() {
    let first = mlkem768_encapsulate(&ENCAPS_EK, &ENCAPS_M).expect("valid key");
    let second = mlkem768_encapsulate(&ENCAPS_EK, &ENCAPS_M).expect("valid key");
    assert_eq!(first.0, second.0);
    assert_eq!(first.1, second.1);

    let mut other_m = ENCAPS_M;
    other_m[0] ^= 0x01;
    let third = mlkem768_encapsulate(&ENCAPS_EK, &other_m).expect("valid key");
    assert_ne!(first.1, third.1);
}

/// FIPS 203 §7.3 implicit rejection: a tampered ciphertext yields a
/// different, deterministic key rather than an error, so an attacker learns
/// nothing from the distinction between a valid and an invalid ciphertext.
#[test]
fn a_forged_ciphertext_is_implicitly_rejected() {
    let key = MlKem768SecretKey::from_seed(&KEYGEN_SEED);
    let (ciphertext, sent) =
        mlkem768_encapsulate(&key.encapsulation_key(), &ENCAPS_M).expect("valid key");

    let mut forged = ciphertext;
    forged[0] ^= 0x01;
    let rejected = key.decapsulate(&forged);
    assert_ne!(rejected, sent);
    // Deterministic: the same forgery always yields the same key, so it is
    // the seed's rejection secret and not uninitialised memory.
    assert_eq!(key.decapsulate(&forged), rejected);
}

/// A malformed encapsulation key is refused rather than steering the
/// result: FIPS 203 requires the encoded coefficients to be canonically
/// reduced.
#[test]
fn a_malformed_encapsulation_key_is_refused() {
    let mut bad = ENCAPS_EK;
    // The final 32 bytes are the seed `rho`, which is unconstrained; the
    // coefficient region is what the reduction check covers.
    for byte in bad.iter_mut().take(MLKEM768_ENCAPSULATION_KEY_LEN - 32) {
        *byte = 0xff;
    }
    assert_eq!(mlkem768_encapsulate(&bad, &ENCAPS_M), Err(KemError(())));
}

#[test]
fn the_widths_are_the_declared_sizes() {
    assert_eq!(MLKEM768_SEED_LEN, 64);
    assert_eq!(MLKEM768_ENCAPSULATION_KEY_LEN, 1184);
    assert_eq!(MLKEM768_CIPHERTEXT_LEN, 1088);
    assert_eq!(MLKEM768_SHARED_KEY_LEN, 32);
}

/// The decapsulation key never reaches a log.
#[test]
fn debug_does_not_leak_the_key() {
    use core::fmt::Write as _;

    struct Sink {
        data: [u8; 128],
        len: usize,
    }
    impl core::fmt::Write for Sink {
        fn write_str(&mut self, s: &str) -> core::fmt::Result {
            let end = self.len + s.len();
            if end > self.data.len() {
                return Err(core::fmt::Error);
            }
            self.data[self.len..end].copy_from_slice(s.as_bytes());
            self.len = end;
            Ok(())
        }
    }

    let key = MlKem768SecretKey::from_seed(&KEYGEN_SEED);
    let mut sink = Sink {
        data: [0; 128],
        len: 0,
    };
    write!(&mut sink, "{key:?}").expect("fits");
    let rendered = core::str::from_utf8(&sink.data[..sink.len]).expect("ascii");
    assert!(rendered.contains("MlKem768SecretKey"));
    assert!(!rendered.contains("0x"), "no key bytes may be rendered");
}
