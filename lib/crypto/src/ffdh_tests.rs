/// A shared secret keeps its leading zero bytes: the value is the modulus
/// width, so a caller can tell a small value from a stripped one.
#[test]
fn a_value_is_always_the_modulus_width() {
    assert_eq!(GROUP14_SHARED.len(), FFDH_GROUP14_LEN);
    assert_eq!(GROUP16_SHARED.len(), FFDH_GROUP16_LEN);
    assert_eq!(GROUP18_SHARED.len(), FFDH_GROUP18_LEN);
    assert_eq!(FFDH_GROUP14_LEN, 256);
    assert_eq!(FFDH_GROUP16_LEN, 512);
    assert_eq!(FFDH_GROUP18_LEN, 1024);
}

/// The generator is 2, so the exponent 1 yields it directly — a cheap check
/// that the group constant really is the one RFC 3526 fixes.
#[test]
fn the_generator_is_two() {
    let mut one = [0u8; FFDH_GROUP14_LEN];
    one[FFDH_GROUP14_LEN - 1] = 1;
    let mut two = [0u8; FFDH_GROUP14_LEN];
    two[FFDH_GROUP14_LEN - 1] = 2;
    assert_eq!(ffdh_group14_public(&one).expect("valid"), two);
}

/// Zero is not a private exponent, and neither is a value at or above the
/// modulus.
#[test]
fn an_invalid_exponent_is_refused() {
    assert_eq!(
        ffdh_group14_public(&[0u8; FFDH_GROUP14_LEN]),
        Err(FfdhError(()))
    );
    assert_eq!(
        ffdh_group14_public(&[0xffu8; FFDH_GROUP14_LEN]),
        Err(FfdhError(()))
    );
    assert_eq!(
        ffdh_group14_agree(&[0u8; FFDH_GROUP14_LEN], &GROUP14_Y_B),
        Err(FfdhError(()))
    );
}

/// The peer values that generate a small subgroup — 0, 1, and `p - 1`, plus
/// `p` itself and anything above it — are refused, because each would let
/// the peer dictate the shared secret rather than contribute to it.
#[test]
fn a_small_subgroup_peer_value_is_refused() {
    let mut zero = [0u8; FFDH_GROUP14_LEN];
    let mut one = [0u8; FFDH_GROUP14_LEN];
    one[FFDH_GROUP14_LEN - 1] = 1;

    // `p` and `p - 1` in full width: `p` is all-ones in its top and bottom
    // 64 bits, so `p - 1` differs from `p` only in the last byte.
    let p_minus_one = super::FFDH_GROUP14_MODULUS
        .wrapping_sub(&crypto_bigint::U2048::ONE)
        .to_be_bytes();
    let mut pm1 = [0u8; FFDH_GROUP14_LEN];
    pm1.copy_from_slice(p_minus_one.as_ref());
    let p = super::FFDH_GROUP14_MODULUS.to_be_bytes();
    let mut modulus = [0u8; FFDH_GROUP14_LEN];
    modulus.copy_from_slice(p.as_ref());

    for bad in [zero, one, pm1, modulus, [0xffu8; FFDH_GROUP14_LEN]] {
        assert_eq!(
            ffdh_group14_agree(&GROUP14_X_A, &bad),
            Err(FfdhError(())),
            "a degenerate peer value must be refused"
        );
    }

    // A legitimate peer value still works, so the check is not refusing
    // everything.
    zero[FFDH_GROUP14_LEN - 1] = 2;
    assert!(ffdh_group14_agree(&GROUP14_X_A, &zero).is_ok());
}

/// A different exponent reaches a different secret, so the agreement really
/// depends on both sides.
#[test]
fn the_secret_depends_on_the_exponent() {
    let mut other = GROUP14_X_A;
    other[FFDH_GROUP14_LEN - 1] ^= 0x01;
    assert_ne!(
        ffdh_group14_agree(&other, &GROUP14_Y_B).expect("valid"),
        GROUP14_SHARED
    );
}
