#[test]
fn one_shot_matches_the_fips_vectors() {
    assert_eq!(sha256(b""), SHA256_EMPTY);
    assert_eq!(sha256(b"abc"), SHA256_ABC);
    assert_eq!(sha384(b""), SHA384_EMPTY);
    assert_eq!(sha384(b"abc"), SHA384_ABC);
    assert_eq!(sha512(b""), SHA512_EMPTY);
    assert_eq!(sha512(b"abc"), SHA512_ABC);
}

#[test]
fn output_lengths_are_the_declared_widths() {
    assert_eq!(SHA256_OUTPUT_LEN, 32);
    assert_eq!(SHA384_OUTPUT_LEN, 48);
    assert_eq!(SHA512_OUTPUT_LEN, 64);
}

/// Any split of the same message must give the digest of the whole: the
/// streaming wrapper shares the one-shot's core, so a disagreement means the
/// wrapper restarted, dropped, or reordered a chunk.
#[test]
fn streaming_matches_the_one_shot_across_chunk_boundaries() {
    let msg = message();
    let splits = [0usize, 1, 31, 32, 33, 63, 64, 65, 95, 96];

    for split in splits {
        let (a, b) = msg.split_at(split);

        let mut s256 = Sha256Stream::new();
        s256.update(a);
        s256.update(b);
        assert_eq!(s256.finalize(), sha256(&msg), "sha256 split at {split}");

        let mut s384 = Sha384Stream::new();
        s384.update(a);
        s384.update(b);
        assert_eq!(s384.finalize(), sha384(&msg), "sha384 split at {split}");

        let mut s512 = Sha512Stream::new();
        s512.update(a);
        s512.update(b);
        assert_eq!(s512.finalize(), sha512(&msg), "sha512 split at {split}");
    }
}

/// A stream fed nothing is the empty-message digest, and `Default` is `new`.
#[test]
fn an_unfed_stream_is_the_empty_digest() {
    assert_eq!(Sha256Stream::default().finalize(), SHA256_EMPTY);
    assert_eq!(Sha384Stream::default().finalize(), SHA384_EMPTY);
    assert_eq!(Sha512Stream::default().finalize(), SHA512_EMPTY);
}

/// SHA-384 is not a truncation of the SHA-512 this crate exposes: they use
/// different initial state, so a wrapper that wired SHA-384 to SHA-512's core
/// and cut the output would fail here.
#[test]
fn sha384_is_not_a_prefix_of_sha512() {
    assert_ne!(SHA384_ABC[..], SHA512_ABC[..SHA384_OUTPUT_LEN]);
}

/// Empty and non-empty inputs produce different digests for every variant —
/// a wrapper that ignored its input would pass the empty vectors alone.
#[test]
fn distinct_messages_give_distinct_digests() {
    assert_ne!(sha256(b""), sha256(b"abc"));
    assert_ne!(sha384(b""), sha384(b"abc"));
    assert_ne!(sha512(b""), sha512(b"abc"));
}
