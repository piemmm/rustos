/// Signing must reproduce RFC 6979's deterministic `(r, s)` on all three
/// curves. This is the test that distinguishes a deterministic signer from a
/// randomised one: a randomised nonce gives a different `(r, s)` every run
/// and could never match a published vector.
#[test]
fn signing_matches_the_rfc6979_vectors() {
    let key = P256SecretKey::from_scalar(&P256_X).expect("valid scalar");
    assert_eq!(key.sign(SAMPLE), (P256_R, P256_S));

    let key = P384SecretKey::from_scalar(&P384_X).expect("valid scalar");
    assert_eq!(key.sign(SAMPLE), (P384_R, P384_S));

    let key = P521SecretKey::from_scalar(&P521_X).expect("valid scalar");
    assert_eq!(key.sign(SAMPLE), (P521_R, P521_S));
}

/// Signing twice gives the same signature, which is the property a
/// deterministic nonce buys and the one a biased RNG would destroy.
#[test]
fn signing_is_repeatable() {
    let key = P521SecretKey::from_scalar(&P521_X).expect("valid scalar");
    assert_eq!(key.sign(SAMPLE), key.sign(SAMPLE));
    assert_ne!(key.sign(SAMPLE), key.sign(b"a different message"));
}

#[test]
fn the_public_key_matches_the_vector_point() {
    assert_eq!(
        P256SecretKey::from_scalar(&P256_X)
            .expect("valid")
            .public_key()
            .to_sec1_uncompressed(),
        P256_POINT
    );
    assert_eq!(
        P384SecretKey::from_scalar(&P384_X)
            .expect("valid")
            .public_key()
            .to_sec1_uncompressed(),
        P384_POINT
    );
    assert_eq!(
        P521SecretKey::from_scalar(&P521_X)
            .expect("valid")
            .public_key()
            .to_sec1_uncompressed(),
        P521_POINT
    );
}

#[test]
fn verification_accepts_the_vector_signatures() {
    P256PublicKey::from_sec1(&P256_POINT)
        .expect("valid point")
        .verify(SAMPLE, &P256_R, &P256_S)
        .expect("vector verifies");
    P384PublicKey::from_sec1(&P384_POINT)
        .expect("valid point")
        .verify(SAMPLE, &P384_R, &P384_S)
        .expect("vector verifies");
    P521PublicKey::from_sec1(&P521_POINT)
        .expect("valid point")
        .verify(SAMPLE, &P521_R, &P521_S)
        .expect("vector verifies");
}

/// Altering the message, either scalar, or the key must be refused.
#[test]
fn verification_rejects_every_alteration() {
    let key = P256PublicKey::from_sec1(&P256_POINT).expect("valid point");
    assert_eq!(
        key.verify(b"not sample", &P256_R, &P256_S),
        Err(NistCurveError(()))
    );

    let mut bad_r = P256_R;
    bad_r[0] ^= 0x01;
    assert_eq!(key.verify(SAMPLE, &bad_r, &P256_S), Err(NistCurveError(())));

    let mut bad_s = P256_S;
    bad_s[31] ^= 0x01;
    assert_eq!(key.verify(SAMPLE, &P256_R, &bad_s), Err(NistCurveError(())));

    let other = P384PublicKey::from_sec1(&P384_POINT).expect("valid point");
    assert_eq!(
        other.verify(SAMPLE, &P384_R, &P256_S_WIDENED),
        Err(NistCurveError(()))
    );
}

/// `P384_S` padded is not `P256_S`; a distinct in-range scalar that is not
/// the right one must fail rather than be accepted by a lax check.
const P256_S_WIDENED: [u8; P384_SCALAR_LEN] = {
    let mut out = [0u8; P384_SCALAR_LEN];
    let mut i = 0;
    while i < P256_SCALAR_LEN {
        out[P384_SCALAR_LEN - P256_SCALAR_LEN + i] = P256_S[i];
        i += 1;
    }
    out
};

/// A zero scalar is not a signature component and must be refused before it
/// reaches the curve.
#[test]
fn verification_rejects_a_zero_scalar() {
    let key = P256PublicKey::from_sec1(&P256_POINT).expect("valid point");
    assert_eq!(
        key.verify(SAMPLE, &[0u8; P256_SCALAR_LEN], &P256_S),
        Err(NistCurveError(()))
    );
    assert_eq!(
        key.verify(SAMPLE, &P256_R, &[0u8; P256_SCALAR_LEN]),
        Err(NistCurveError(()))
    );
}

#[test]
fn ecdh_matches_the_wycheproof_vectors() {
    let peer = P256PublicKey::from_sec1(&P256_ECDH_PEER).expect("valid point");
    let key = P256SecretKey::from_scalar(&P256_ECDH_PRIVATE).expect("valid scalar");
    assert_eq!(key.agree(&peer), P256_ECDH_SHARED);

    let peer = P384PublicKey::from_sec1(&P384_ECDH_PEER).expect("valid point");
    let key = P384SecretKey::from_scalar(&P384_ECDH_PRIVATE).expect("valid scalar");
    assert_eq!(key.agree(&peer), P384_ECDH_SHARED);

    let peer = P521PublicKey::from_sec1(&P521_ECDH_PEER).expect("valid point");
    let key = P521SecretKey::from_scalar(&P521_ECDH_PRIVATE).expect("valid scalar");
    assert_eq!(key.agree(&peer), P521_ECDH_SHARED);
}

/// Both sides of an exchange reach the same secret, and a third party's key
/// reaches a different one.
#[test]
fn ecdh_is_symmetric_and_key_dependent() {
    let alice = P256SecretKey::from_scalar(&P256_X).expect("valid scalar");
    let bob = P256SecretKey::from_scalar(&P256_ECDH_PRIVATE).expect("valid scalar");
    assert_eq!(
        alice.agree(&bob.public_key()),
        bob.agree(&alice.public_key())
    );

    let mallory_scalar = {
        let mut s = P256_ECDH_PRIVATE;
        s[31] ^= 0x01;
        s
    };
    let mallory = P256SecretKey::from_scalar(&mallory_scalar).expect("valid scalar");
    assert_ne!(
        alice.agree(&bob.public_key()),
        alice.agree(&mallory.public_key())
    );
}

/// A point that is not on the curve, the identity, or a wrong-length string
/// is refused at decode rather than reaching an operation.
#[test]
fn a_malformed_point_is_refused_at_decode() {
    let mut off_curve = P256_POINT;
    off_curve[64] ^= 0x01;
    assert_eq!(
        P256PublicKey::from_sec1(&off_curve),
        Err(NistCurveError(()))
    );

    assert_eq!(P256PublicKey::from_sec1(&[]), Err(NistCurveError(())));
    assert_eq!(P256PublicKey::from_sec1(&[0x00]), Err(NistCurveError(())));
    assert_eq!(
        P256PublicKey::from_sec1(&P256_POINT[..64]),
        Err(NistCurveError(()))
    );
    // A P-384 point is not a P-256 point.
    assert_eq!(
        P256PublicKey::from_sec1(&P384_POINT),
        Err(NistCurveError(()))
    );
}

/// The compressed form of the same point decodes to the same key, so a peer
/// choosing either encoding is accepted and re-encodes canonically.
#[test]
fn a_compressed_point_decodes_to_the_same_key() {
    let uncompressed = P256PublicKey::from_sec1(&P256_POINT).expect("valid point");
    let mut compressed = [0u8; 33];
    compressed[0] = if P256_POINT[P256_POINT_LEN - 1] & 1 == 1 {
        0x03
    } else {
        0x02
    };
    compressed[1..].copy_from_slice(&P256_POINT[1..33]);
    let from_compressed = P256PublicKey::from_sec1(&compressed).expect("valid point");
    assert_eq!(
        from_compressed.to_sec1_uncompressed(),
        uncompressed.to_sec1_uncompressed()
    );
}

/// A zero scalar and the curve order are not private keys.
#[test]
fn an_out_of_range_scalar_is_refused() {
    assert_eq!(
        P256SecretKey::from_scalar(&[0u8; P256_SCALAR_LEN]).err(),
        Some(NistCurveError(()))
    );
    assert_eq!(
        P256SecretKey::from_scalar(&[0xffu8; P256_SCALAR_LEN]).err(),
        Some(NistCurveError(()))
    );
}

/// The private scalar round-trips, so a key file written from it reloads to
/// the same key.
#[test]
fn the_scalar_round_trips() {
    let key = P521SecretKey::from_scalar(&P521_X).expect("valid scalar");
    assert_eq!(key.scalar(), P521_X);
    let reloaded = P521SecretKey::from_scalar(&key.scalar()).expect("valid scalar");
    assert_eq!(
        reloaded.public_key().to_sec1_uncompressed(),
        key.public_key().to_sec1_uncompressed()
    );
}

/// The private scalar never reaches a log.
#[test]
fn debug_does_not_leak_the_scalar() {
    use core::fmt::Write as _;

    struct Sink {
        data: [u8; 128],
        len: usize,
    }
    impl core::fmt::Write for Sink {
        fn write_str(&mut self, s: &str) -> core::fmt::Result {
            let end = self.len + s.len();
            if end > self.data.len() {
                return Err(core::fmt::Error);
            }
            self.data[self.len..end].copy_from_slice(s.as_bytes());
            self.len = end;
            Ok(())
        }
    }

    let key = P256SecretKey::from_scalar(&P256_X).expect("valid scalar");
    let mut sink = Sink {
        data: [0; 128],
        len: 0,
    };
    write!(&mut sink, "{key:?}").expect("fits");
    let rendered = core::str::from_utf8(&sink.data[..sink.len]).expect("ascii");
    assert!(rendered.contains("P256SecretKey"));
    assert!(
        !rendered.contains("c9"),
        "scalar bytes must not be rendered"
    );
}
