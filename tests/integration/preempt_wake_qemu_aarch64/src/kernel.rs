//! The freestanding aarch64 test kernel: spawn one SOLE EL0 spinner (no
//! competitor, so the tickless scheduler never arms the preemption timer),
//! have its kthread send itself a reschedule SGI just before entering EL0,
//! and prove that non-timer interrupt drives the return-to-EL0 preempt point
//! via the need-resched latch — the regression test for the
//! interrupt-return-to-EL0 need-resched fix.

