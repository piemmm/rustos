/// Bring the board up: FP/SIMD on, the `virt` device tree discovered
/// (timer rate, GICv2 bases), the identity-gigapage masks configured from
/// the board facts, the identity MMU + EL1 vectors enabled, the GIC
/// initialised, and the dispatch callback + user-fault resolver installed.
/// Returns the discovered generic-timer rate.
fn bring_up_board() -> u64 {
    // Enable FP/SIMD at EL1 before any code the compiler may lower to NEON
    // (the `rxe` decoder, the spawn image fills, the log formatter).
    // SAFETY: this is the boot CPU, called once, before any FP/SIMD executes.
    unsafe { enable_fp_el1() };

    let Ok(fdt) = Fdt::new(DTB_BLOB) else {
        qemu_exit::exit_failure(FAIL_GIC);
    };
    let counter_hz = timer_frequency_hz(&fdt);
    if counter_hz == 0 {
        qemu_exit::exit_failure(FAIL_ZERO_FREQ);
    }
    if gic::configure_from_fdt(&fdt).is_none() {
        qemu_exit::exit_failure(FAIL_GIC);
    }

    // Configure the identity gigapage masks from the `virt` board facts
    // (Device GiB 0 — the MMIO window — and RAM GiB 1), exactly as the
    // production boot path derives them from discovery: the production
    // spawn producer sizes every child's identity window from these masks,
    // so driving it under the unconfigured defaults would request a window
    // reaching the user bias and the spawn would fail closed.
    let mut device_mask = [0u64; GIGAPAGE_MASK_WORDS];
    device_mask[0] = 0b01;
    configure_device_gigapages(device_mask);
    let mut ram_mask = [0u64; GIGAPAGE_MASK_WORDS];
    ram_mask[0] = 0b10;
    configure_ram_gigapages(ram_mask);

    // Enable the identity MMU + EL1 vectors before any atomic
    // read-modify-write runs: the frame allocator, the scheduler, and every
    // registry the test builds use atomics, which are UNPREDICTABLE on
    // MMU-off Device-typed memory (`plans/PI.md` P6c-2).
    let Some(boot_space) =
        ArchAddressSpace::new_identity_gigapages(&BOOT_PAGE_TABLES, IDENTITY_GIB)
    else {
        qemu_exit::exit_failure(FAIL_POOL);
    };
    // SAFETY: the identity map covers the kernel's current `pc`, `sp`, the
    // heap, the frame pool, and the device MMIO (all within `[0, 2 GiB)` on
    // the `virt` board), so switching it does not move the ground under the
    // running code; `init_vectors` runs once on the boot CPU with a stack
    // established.
    unsafe {
        boot_space.switch();
        exceptions::init_vectors();
    }
    // The boot space's tables live in the static `BOOT_PAGE_TABLES` pool
    // and the handle carries no `Drop`, so letting it fall out of scope
    // leaves the active translation regime untouched for the kernel's
    // lifetime (the kernel never returns).
    // SAFETY: called once on the boot CPU after the GIC bases were
    // discovered above.
    unsafe {
        gic::init();
    }
    syscall_entry::set_dispatch_callback(dispatch);
    // Bind the production user-fault resolver to this vertical's slot — the
    // fault-driven growth heart this test exists to prove.
    if fault::set_user_fault_resolver(mem_pin_user_fault).is_err() {
        qemu_exit::exit_failure(FAIL_RESOLVER_INSTALL);
    }
    counter_hz
}

/// The leaked-`'static` kernel subsystems the production dispatch hook and
/// spawn context borrow — the vertical's analogue of `KernelState`, lifted
/// by one-shot `Box::leak` publishes exactly as `kernel_core::kernel_main`
/// does (a one-shot publish, not a global mutable static).
struct Subsystems {
    frames: &'static FrameAllocator,
    sched: &'static Scheduler<Aarch64BinArch>,
    arch: &'static Aarch64BinArch,
    caps: &'static RwLock<CapTable>,
    ipc: &'static RwLock<PortRegistry>,
    aspaces: &'static RwLock<AddressSpaceRegistry>,
    rng: &'static RwLock<Box<dyn RandomReserve + Send + Sync>>,
    irq_table: &'static IrqTable,
}

/// Build the live kernel subsystems: the `kernel/mem` frame allocator over
/// the identity-mapped pool (so the spawn producer and the demand-fault
/// path draw their frames from the production path), the scheduler over
/// the production `KernelArch` wrapper, and the capability / port /
/// address-space / random / IRQ state the production hook borrows.
fn leak_subsystems(counter_hz: u64) -> Subsystems {
    let mut memory_map = BootMemoryMap::new();
    memory_map.push(MemoryRegion {
        start: PhysAddr::new(core::ptr::addr_of!(FRAME_POOL) as u64),
        length: (PAGE_SIZE * FRAME_COUNT) as u64,
        kind: RegionKind::Usable,
    });
    let Ok(frames) = FrameAllocator::new(&memory_map) else {
        qemu_exit::exit_failure(FAIL_FRAMES);
    };
    let frames: &'static FrameAllocator = Box::leak(Box::new(frames));

    let sched_inner = Aarch64Arch::with_cpus(
        &SCHED_STORAGE,
        BOOT_CPU,
        counter_hz,
        &CPU_MPIDRS[..CPU_COUNT as usize],
    );
    let hook_inner = Aarch64Arch::with_cpus(
        &HOOK_ARCH_STORAGE,
        BOOT_CPU,
        counter_hz,
        &CPU_MPIDRS[..CPU_COUNT as usize],
    );
    #[cfg(migration_smp)]
    let (sched_inner, hook_inner) = {
        let method = Fdt::new(DTB_BLOB)
            .ok()
            .and_then(|fdt| tairix_arch_aarch64::fdt::psci_method(&fdt))
            .unwrap_or_else(|| qemu_exit::exit_failure(FAIL_SECONDARY));
        (
            sched_inner.with_secondary_start(SecondaryStart::Psci(method)),
            hook_inner.with_secondary_start(SecondaryStart::Psci(method)),
        )
    };
    let sched_arch = Arc::new(Aarch64BinArch::new(sched_inner));
    let Ok(sched) = Scheduler::new(SchedulerConfig::defaults_for(CPU_COUNT), sched_arch) else {
        qemu_exit::exit_failure(FAIL_SCHED_NEW);
    };

    Subsystems {
        frames,
        sched: Box::leak(Box::new(sched)),
        arch: Box::leak(Box::new(Aarch64BinArch::new(hook_inner))),
        caps: Box::leak(Box::new(RwLock::new(CapTable::new()))),
        ipc: Box::leak(Box::new(RwLock::new(PortRegistry::new()))),
        aspaces: Box::leak(Box::new(RwLock::new(AddressSpaceRegistry::new()))),
        rng: Box::leak(Box::new(RwLock::new(
            Box::new(BootReserve::new()) as Box<dyn RandomReserve + Send + Sync>
        ))),
        irq_table: Box::leak(Box::new(IrqTable::new(0))),
    }
}

/// Register the private migration endpoint and spawn its event-driven echo
/// server as a real scheduler kthread.
fn install_echo_server(sys: &Subsystems) {
    let empty = CapabilitySet::empty();
    let creator = TaskCapabilities::derive(
        ProcessId(0x4d49_4752),
        UserId(0),
        empty,
        empty,
        &SERIAL_SINK,
    );
    let endpoint = match CallEndpoint::create(
        EndpointId(MIGRATION_ENDPOINT),
        &creator,
        CapabilitySet::empty(),
        CapabilitySet::empty(),
        CallEndpointLimits {
            max_request: 8,
            max_reply: 8,
            capacity: 8,
        },
        &SERIAL_SINK,
    ) {
        Ok(endpoint) => Arc::new(endpoint),
        Err(_) => qemu_exit::exit_failure(FAIL_ENDPOINT),
    };
    if tairix_kernel_core::callreg::register(Arc::clone(&endpoint), &SERIAL_SINK).is_err() {
        qemu_exit::exit_failure(FAIL_ENDPOINT);
    }
    let server_id = Arc::new(AtomicU64::new(0));
    let body_id = Arc::clone(&server_id);
    let body_endpoint = Arc::clone(&endpoint);
    let server = spawn_kthread(
        sys.sched,
        ContextSwitchHal::new(),
        BOOT_CPU,
        Priority::High,
        move |yielder: &mut Yielder<ContextSwitchHal>| {
            let id = body_id.load(Ordering::Acquire);
            body_endpoint.record_server_task(id);
            loop {
                tairix_kernel_core::waitq::SERVE_WAITQ
                    .register(id, tairix_kernel_core::waitq::NO_DEADLINE);
                match body_endpoint.recv_call(8) {
                    RecvCall::Received(call) => {
                        tairix_kernel_core::waitq::SERVE_WAITQ.deregister(id);
                        let poster =
                            match body_endpoint.reply(call.ticket, &call.request, &SERIAL_SINK) {
                                Ok(poster) => poster,
                                Err(_) => qemu_exit::exit_failure(FAIL_SERVER),
                            };
                        tairix_kernel_core::waitq::call_wake_task(poster);
                    }
                    RecvCall::Empty => {
                        yielder.park();
                        tairix_kernel_core::waitq::SERVE_WAITQ.deregister(id);
                    }
                    RecvCall::TooLarge { .. } => qemu_exit::exit_failure(FAIL_SERVER),
                }
            }
        },
    );
    let Ok(server) = server else {
        qemu_exit::exit_failure(FAIL_SERVER);
    };
    server_id.store(server, Ordering::Release);
}

/// Drive CPU 0 until the kernel-parented `pid` exits and return its code.
fn drive_process(sys: &Subsystems, wait: &KernelProcessWait<Aarch64BinArch>, pid: u64) -> i32 {
    // A kernel-minted process id round-trips through the `i32` the wait ABI
    // carries.
    #[allow(clippy::cast_possible_truncation, clippy::cast_possible_wrap)]
    let pid = pid as i32;
    for _ in 0..MAX_STEPS {
        let _ = sys.sched.step(BOOT_CPU);
        let _ = tairix_kernel_core::waitq::drain_pending_wakes();
        match wait.poll(ProcessId(0), pid, WaitFlags::empty()) {
            Ok(reaped) => match reaped.status {
                WaitStatus::Exited(code) => return code,
                WaitStatus::Stopped(_) => qemu_exit::exit_failure(FAIL_PARENT_STOPPED),
            },
            Err(Errno::WouldBlock) => {}
            Err(_) => qemu_exit::exit_failure(FAIL_POLL),
        }
    }
    qemu_exit::exit_failure(FAIL_DEADLOCK)
}

#[cfg(migration_smp)]
extern "C" fn migration_ipi(cpu: CpuId) {
    tairix_kernel_core::note_preempt_tick(cpu);
}

#[cfg(migration_smp)]
extern "C" fn migration_preempt(cpu: CpuId) {
    let _ = tairix_kernel_core::preempt_current(cpu);
}

/// Secondary-core entry for the four-vCPU migration package.
#[cfg(migration_smp)]
extern "C" fn migration_secondary(cpu: CpuId) -> ! {
    // SAFETY: the boot core published the permanent identity root before
    // issuing CPU_ON; this secondary has not enabled interrupts yet.
    if !unsafe { tairix_arch_aarch64::paging::adopt_boot_translation() } {
        qemu_exit::exit_failure(FAIL_SECONDARY);
    }
    // SAFETY: per-CPU vector/GIC/SGI setup on this secondary, exactly once.
    unsafe {
        exceptions::init_vectors();
        gic::init();
        preempt::enable_ipi();
        exceptions::enable_irq();
    }
    SMP_ONLINE.fetch_or(1u32 << cpu, Ordering::Release);
    let scheduler = SMP_SCHEDULER.load(Ordering::Acquire);
    if scheduler.is_null() {
        qemu_exit::exit_failure(FAIL_SECONDARY);
    }
    // SAFETY: `start_migration_secondaries` publishes the leaked scheduler
    // before CPU_ON and it remains live for the kernel's lifetime.
    let scheduler = unsafe { &*scheduler };
    loop {
        if SMP_PAUSED.load(Ordering::Acquire) & (1u32 << cpu) != 0 {
            // Deliberately paused by the controller. Park until the release
            // IPI, closing the pause/wake race the same way the production
            // dispatch loop closes the idle/wake race: mask IRQ *taking*,
            // re-check the pause under the mask, and `wfi` only while still
            // paused. The release IPI then arrives pending-but-masked and
            // still wakes the `wfi`, so it is never dropped by the handler
            // acknowledging it just before the park. Restore taking
            // (dispatching the IPI) before re-checking at the loop top.
            //
            // SAFETY: `mask_irq`/`enable_irq` toggle `DAIF.I` only; this
            // secondary's vectors + GICv2 are live, so a taken IPI
            // dispatches through a valid handler.
            unsafe { exceptions::mask_irq() };
            if SMP_PAUSED.load(Ordering::Acquire) & (1u32 << cpu) != 0 {
                // SAFETY: `wfi` wakes on the pending-but-masked release IPI;
                // no lock is held across the park.
                unsafe { exceptions::wait_for_interrupt() };
            }
            // SAFETY: restore IRQ taking so the release IPI is dispatched.
            unsafe { exceptions::enable_irq() };
            continue;
        }
        let outcome = scheduler.step(cpu);
        if matches!(outcome, Ok(StepOutcome::Idle)) {
            // Tickless idle park under the production park/wake protocol
            // (`kernel_core::init::run_dispatch_loop`): mask IRQ taking,
            // then — under the mask — drain any flagged wake and re-check
            // both for ready work (a placement IPI landing during the step
            // enqueued a just-woken task here) and a fresh pause request,
            // and `wfi` only if still genuinely idle. A placement or release
            // IPI landing in the check->park window stays pending-but-masked
            // and wakes the `wfi`, so a readied task can never be stranded
            // on this sleeping CPU (the lost-wakeup that stalled this
            // vertical under the full matrix). Restore taking afterwards so
            // the pending IPI dispatches.
            //
            // SAFETY: `mask_irq`/`enable_irq` toggle `DAIF.I` only; vectors
            // + GICv2 are live on this CPU.
            unsafe { exceptions::mask_irq() };
            let woke = tairix_kernel_core::waitq::drain_pending_wakes();
            let ready = scheduler.has_ready_work(cpu).unwrap_or(false);
            let paused = SMP_PAUSED.load(Ordering::Acquire) & (1u32 << cpu) != 0;
            if !(woke || ready || paused) {
                // SAFETY: `wfi` wakes on a pending-but-masked interrupt (the
                // scheduler's placement IPI when work lands here, a device
                // IRQ, or the controller's release IPI); no lock is held.
                unsafe { exceptions::wait_for_interrupt() };
            }
            // SAFETY: restore IRQ taking so the pending interrupt dispatches.
            unsafe { exceptions::enable_irq() };
        } else {
            // A task ran (or a benign step error): drain deferred wakes in
            // dispatcher context with IRQ taking enabled, matching the
            // production loop's between-dispatch servicing.
            let _ = tairix_kernel_core::waitq::drain_pending_wakes();
        }
    }
}

/// Start CPUs 1..3 and wait until their dispatch loops are live.
#[cfg(migration_smp)]
fn start_migration_secondaries(sys: &Subsystems) {
    static STACKS: smp::SecondaryStackPool<4> = smp::SecondaryStackPool::new();
    SMP_SCHEDULER.store(sys.sched as *const _ as *mut _, Ordering::Release);
    if STACKS.register().is_err() || smp::set_secondary_entry(migration_secondary).is_err() {
        qemu_exit::exit_failure(FAIL_SECONDARY);
    }
    preempt::set_ipi_callback(migration_ipi);
    preempt::set_preempt_callback(migration_preempt);
    // SAFETY: boot CPU vectors/GIC are live and callbacks are installed.
    unsafe {
        preempt::enable_ipi();
        exceptions::enable_irq();
    }
    for cpu in 1..CPU_COUNT {
        // SAFETY: topology, stack pool, and callback are published; each id
        // names a distinct parked QEMU CPU.
        if unsafe { sys.arch.arch().start_secondary(cpu) }.is_err() {
            qemu_exit::exit_failure(FAIL_SECONDARY);
        }
    }
    let expected = ((1u32 << CPU_COUNT) - 1) & !1;
    while SMP_ONLINE.load(Ordering::Acquire) != expected {
        core::hint::spin_loop();
    }
}

/// Boot entry point — the symbol the arch crate's `boot.s` trampoline calls
/// (via `tairix_arch_aarch64_main`).
#[no_mangle]
pub extern "C" fn kernel_main(_dtb: u64) -> ! {
    note(TEST_START, "aarch64 mem-pin test: starting");

    let counter_hz = bring_up_board();

    // The fixture `rxe`'s baked relocations must target the bias the
    // production producer maps every child at; a drifted constant would
    // admit a child whose pointers do not match its mapping (fail closed).
    if USER_BIAS != USER_IMAGE_BIAS {
        qemu_exit::exit_failure(FAIL_BIAS);
    }

    let sys = leak_subsystems(counter_hz);

    // Publish the wait-queue arch hook so parked waiters (the parent in
    // `wait`) are genuinely unparked by their wake events — the same
    // adapter the production boot path installs.
    let wait_arch: &'static ChassisWaitArch = Box::leak(Box::new(ChassisWaitArch {
        scheduler: sys.sched,
        arch: sys.arch,
    }));
    if tairix_kernel_core::waitq::install_wait_arch(wait_arch).is_err() {
        qemu_exit::exit_failure(FAIL_HOOK_INSTALL);
    }
    install_echo_server(&sys);

    // The scheduler-side process-wait producer: records every parent/child
    // link the production spawn paths register and backs the production
    // `wait` syscall the parent blocks in.
    let wait_producer: &'static KernelProcessWait<Aarch64BinArch> =
        Box::leak(Box::new(KernelProcessWait::new(sys.arch)));

    // The production live-space producer: serves the `mem_map` pair (the
    // `tairix-rt` heap) and — the point of this vertical — the one-page-
    // per-fault backing the stack-growth resolver maps through it.
    let live: &'static LiveMemMap<Aarch64BinArch> = Box::leak(Box::new(LiveMemMap::new(sys.arch)));

    // Publish the production dispatch hook: every syscall the programs
    // issue — `spawn`, `wait`, `rlimit_set`, `exit` — and every user-fault
    // resolution runs the production caller-context resolution and handler
    // path.
    let hook: &'static KernelDispatchHook<'static, Aarch64BinArch> =
        Box::leak(Box::new(KernelDispatchHook::new(
            sys.sched,
            sys.caps,
            sys.arch,
            &SERIAL_SINK,
            sys.irq_table,
            &IRQ_CONTROLLER,
            sys.ipc,
            sys.aspaces,
            sys.rng,
            &UART_ONLY_CONSOLES,
            sys.frames,
            sys.frames,
            &PROGRAMS,
            wait_producer,
            // No seat / MMIO / DMA surface in this vertical; those
            // producers stay fail-closed. No filesystem or file-map
            // producer either: the only faults this vertical exists to
            // exercise are stack growth, the `StackBytes` bound, and the
            // below-span guard.
            &NULL_SEAT_REGISTRY,
            live,
            &NULL_MMIO_MAP_FACILITY,
            &NULL_DMA_ALLOC_FACILITY,
        )));
    if DISPATCH_SLOT.install_dispatcher(hook).is_err() {
        qemu_exit::exit_failure(FAIL_HOOK_INSTALL);
    }
    #[cfg(migration_smp)]
    start_migration_secondaries(&sys);

    // Spawn the parent role through the production runtime-spawn seam
    // (`KernelSpawnCtx` assembly inside `KernelInitSpawner`), recorded
    // against the kernel supervisor identity so this chassis can reap it.
    // Publish the launch-services bundle the deferred child-load path reads:
    // the arch image builder builds each admitted child's image on the
    // child's own first slice, off this chassis's cooperative drive. The one
    // shared build+publish the production boot path uses.
    let _ = tairix_kernel_core::spawn_services::install_over(
        sys.arch,
        sys.frames,
        &SERIAL_SINK,
        &tairix_kernel_core::NULL_FILESYSTEM,
        None,
        sys.aspaces,
        sys.caps,
        wait_producer,
        &AARCH64_PROCESS_SPAWN,
    );

    let init_ctx = KernelInitSpawner::new(
        sys.frames,
        &SERIAL_SINK,
        sys.sched,
        sys.caps,
        sys.aspaces,
        sys.arch,
        wait_producer,
        sys.irq_table,
        &NULL_SHARED_MEM_FACILITY,
    );
    let Ok(parent_pid) = init_ctx.spawn_driver_process(
        "/bin/mp-parent",
        PROGRAM_RXE,
        parent_caps(),
        &[],
        &[b"mp", b"parent", &PIN_BOUND_ARG],
        None,
    ) else {
        qemu_exit::exit_failure(FAIL_SPAWN);
    };
    note(
        TEST_SPAWNED,
        "aarch64 mem-pin test: parent spawned through the production seam",
    );

    let parent_code = drive_process(&sys, wait_producer, parent_pid);
    if parent_code != 0 {
        // A child code outside the reportable range saturates, so it can
        // neither wrap onto another fixture's code nor overflow the add.
        let code = u16::try_from(parent_code).unwrap_or(u16::MAX);
        qemu_exit::exit_failure(FAIL_EXIT_BASE.saturating_add(code));
    }

    let ipc_pid = match init_ctx.spawn_driver_process(
        "/bin/mp-ipc",
        PROGRAM_RXE,
        CapabilitySet::empty(),
        &[],
        &[b"mp", b"ipc"],
        None,
    ) {
        Ok(pid) => pid,
        Err(_) => qemu_exit::exit_failure(FAIL_SPAWN),
    };

    #[cfg(not(migration_smp))]
    let ipc_code = drive_process(&sys, wait_producer, ipc_pid);

    #[cfg(migration_smp)]
    let (ipc_code, observed_cpus) = {
        // A kernel-minted process id round-trips through the `i32` the wait
        // ABI carries.
        #[allow(clippy::cast_possible_truncation, clippy::cast_possible_wrap)]
        let poll_pid = ipc_pid as i32;
        let mut observed = 0u32;
        let mut last_cpu = None;
        let mut migrations = 0u32;
        let mut exit_code = None;
        // Give up only on a genuine stall — a run of controller iterations in
        // which the child made no progress at all — never after a fixed count
        // of total iterations. This loop spins on the boot CPU while the child
        // advances on the secondaries, so a total-iteration budget would
        // measure how fast this loop spins relative to the child, a ratio the
        // host sets arbitrarily by how it schedules the four vCPU threads; a
        // busy or unevenly co-scheduled host could then exhaust it before a
        // healthy child finishes. Counting only consecutive no-progress
        // iterations makes the give-up independent of host load: any sign the
        // child is still advancing — a drained wake answering its blocking
        // IPC, the child seen running on a secondary, or a fresh forced
        // migration — resets the guard, so a slow-but-live run waits as long
        // as it needs and only a truly wedged child is declared deadlocked.
        let mut guard = StallGuard::new(MAX_STEPS);
        loop {
            let mut progressed = tairix_kernel_core::waitq::drain_pending_wakes();
            let mut running_cpu = None;
            for cpu in 1..CPU_COUNT {
                if sys.sched.current_task(cpu) == Some(ipc_pid) {
                    observed |= 1u32 << cpu;
                    running_cpu = Some(cpu);
                    break;
                }
            }
            if let Some(cpu) = running_cpu {
                progressed = true;
                if last_cpu != Some(cpu) {
                    if let Some(previous) = last_cpu {
                        migrations += 1;
                        SMP_PAUSED.fetch_and(!(1u32 << previous), Ordering::AcqRel);
                        SchedulerArch::send_ipi(sys.arch, previous);
                    }
                    SMP_PAUSED.store(1u32 << cpu, Ordering::Release);
                    last_cpu = Some(cpu);
                }
            }
            // Wake every unpaused secondary so one of them steals the ready
            // caller after its currently observed source dispatcher pauses.
            let paused = SMP_PAUSED.load(Ordering::Acquire);
            for cpu in 1..CPU_COUNT {
                if paused & (1u32 << cpu) == 0 {
                    SchedulerArch::send_ipi(sys.arch, cpu);
                }
            }
            match wait_producer.poll(ProcessId(0), poll_pid, WaitFlags::empty()) {
                Ok(reaped) => match reaped.status {
                    WaitStatus::Exited(code) => {
                        exit_code = Some(code);
                        break;
                    }
                    WaitStatus::Stopped(_) => qemu_exit::exit_failure(FAIL_PARENT_STOPPED),
                },
                Err(Errno::WouldBlock) => {}
                Err(_) => qemu_exit::exit_failure(FAIL_POLL),
            }
            if guard.observe(progressed) {
                break;
            }
        }
        SMP_PAUSED.store(0, Ordering::Release);
        (
            exit_code.unwrap_or_else(|| qemu_exit::exit_failure(FAIL_DEADLOCK)),
            (observed, migrations),
        )
    };

    if ipc_code != 0 {
        // A child code outside the reportable range saturates, so it can
        // neither wrap onto another fixture's code nor overflow the add.
        let code = u16::try_from(ipc_code).unwrap_or(u16::MAX);
        qemu_exit::exit_failure(FAIL_IPC_CONTROL.saturating_add(code));
    }

    #[cfg(migration_smp)]
    if observed_cpus.0.count_ones() < 2 || observed_cpus.1 < 4 {
        // The observed-CPU mask is reported alongside the failure; a mask
        // wider than the report saturates rather than overflowing the add.
        let code = u16::try_from(observed_cpus.0).unwrap_or(u16::MAX);
        qemu_exit::exit_failure(FAIL_NO_MIGRATION.saturating_add(code));
    }

    note(
        TEST_PASS,
        if cfg!(migration_smp) {
            "aarch64 mem-pin test: four-CPU blocking IPC migration passed"
        } else {
            "aarch64 mem-pin test: ST2 roles and one-CPU IPC control passed"
        },
    );
    qemu_exit::exit_success();
}
