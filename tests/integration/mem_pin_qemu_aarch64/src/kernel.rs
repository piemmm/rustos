//! The freestanding aarch64 test kernel: prove the `mem_pin` / `mem_unpin`
//! pair end to end (`plans/STRESSTEST.md` ST2).
//!
//! Unlike the bespoke micro-kernel harnesses, every syscall and every user
//! fault here runs the production `KernelDispatchHook` /
//! `KernelSyscallHandlers` path: the chassis installs the hook through a
//! `DispatchCallbackSlot`, binds the production user-fault resolver to the
//! same slot, wires the production `LiveMemMap` producer (backing
//! `mem_map` and the stack-growth fault path), a real `KernelProcessWait`,
//! and a `ProgramRegistry` carrying the three child roles, their numeric
//! parameters derived from the one shared `spawn_layout` policy. The parent
//! role is spawned through the production
//! `InitSpawnCtx::spawn_driver_process` seam; it spawns and reaps the
//! children through the production `spawn` + `wait` syscalls:
//!
//! * `deny` — holds no `CAP_MEM_PIN`: `mem_pin` is refused
//!   `PermissionDenied` at the dispatcher gate while the ungated
//!   `mem_unpin` still answers success, exits 0;
//! * `pin` — lowers its own `pinned-memory-bytes` bound via `rlimit_set`,
//!   pins itself (idempotently), sees an over-budget `mem_map` refused
//!   `OutOfRange` and a within-budget one succeed, unpins, and sees the
//!   formerly refused map succeed, exits 0;
//! * `child` — spawned by the *pinned* parent: starts unpinned (the mark
//!   is never inherited even though the lowered limit is) so its
//!   over-budget map succeeds, exits 0.
//!
//! The shared source also drives a private production call endpoint. The
//! one-vCPU package is the control; the four-vCPU sibling starts real
//! secondary dispatchers and repeatedly pauses the observed source after the
//! caller blocks so another CPU must steal and resume it. Every reply is
//! checked together with integer/FP, stack, PC, and address-space-local state.

