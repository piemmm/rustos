/// Gigabytes of identity map the boot address space provides: `[0, 2 GiB)`
/// covers the `virt` board's device MMIO (GiB 0) and the RAM base at GiB 1
/// where this kernel, its heap, and the frame pool live.
const IDENTITY_GIB: usize = 2;

/// Physical frames the production spawn producer draws from: four spawned
/// processes (image, eagerly committed stack top, page tables,
/// identity-window tables) plus the fixture's successful anonymous maps
/// (one [`WITHIN_BYTES`] and two [`OVER_BYTES`] regions ≈ 4.25 MiB).
/// Sized from that appetite with generous headroom (16 MiB).
const FRAME_COUNT: usize = 4096;

/// The `pinned-memory-bytes` bound the `pin` role (and the parent) impose
/// on themselves: the eagerly committed stack top plus 1 MiB of headroom.
/// Derived from the one shared policy constant so the budget always sits
/// above the spawn-time footprint (the committed stack) with room for the
/// within-budget map, while every [`OVER_BYTES`] request decisively
/// crosses it.
const PIN_BOUND_BYTES: u64 = USER_STACK_COMMIT_PAGES * PAGE_SIZE as u64 + (1 << 20);

/// Bytes of the within-budget map the pinned `pin` role performs: far
/// inside the 1 MiB headroom above the spawn-time footprint.
const WITHIN_BYTES: u64 = 256 << 10;

/// Bytes of the over-budget map: with the spawn-time footprint at least
/// the committed stack, `footprint + OVER_BYTES` always crosses
/// [`PIN_BOUND_BYTES`] (2 MiB > 1 MiB headroom), while an unpinned
/// process maps it freely.
const OVER_BYTES: u64 = 2 << 20;

/// Longest decimal argument the rows below need (`u64::MAX` is 20 digits).
const DEC_MAX: usize = 20;

/// Render `value` as a fixed-width, zero-padded decimal byte string at
/// compile time. Leading zeroes are harmless: the fixture's parser accepts
/// them, and a fixed width lets the argument live in a `static` the
/// registry row borrows.
const fn dec_bytes(mut value: u64) -> [u8; DEC_MAX] {
    let mut out = [b'0'; DEC_MAX];
    let mut i = DEC_MAX;
    while i > 0 {
        i -= 1;
        out[i] = b'0' + (value % 10) as u8;
        value /= 10;
        if value == 0 {
            break;
        }
    }
    out
}

/// [`PIN_BOUND_BYTES`] as a decimal argument-vector value.
static PIN_BOUND_ARG: [u8; DEC_MAX] = dec_bytes(PIN_BOUND_BYTES);
/// [`WITHIN_BYTES`] as a decimal argument-vector value.
static WITHIN_ARG: [u8; DEC_MAX] = dec_bytes(WITHIN_BYTES);
/// [`OVER_BYTES`] as a decimal argument-vector value.
static OVER_ARG: [u8; DEC_MAX] = dec_bytes(OVER_BYTES);

