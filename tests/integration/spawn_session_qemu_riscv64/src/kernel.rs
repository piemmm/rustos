//! The freestanding riscv64 RV-X3 test kernel: build the **parent** U-mode
//! program, admit it under the live scheduler on the `virt` board, and route
//! its `CAP_PROC_SPAWN`-gated `spawn` `ecall` to a riscv64 `ProcessSpawn`
//! producer that builds the **child** (session) a fresh, hardware-isolated Sv39
//! space through the identity window **without** switching the running parent's
//! `satp`, admitting it **Ready** concurrently (`plans/PI.md` RV-X3, the
//! riscv64 sibling of the `aarch64`/`x86_64` `spawn_session` verticals).

