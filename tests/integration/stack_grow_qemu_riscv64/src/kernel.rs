//! The freestanding riscv64 test kernel: prove the demand-grown user stack
//! end to end on the `virt` board — the riscv64 twin of
//! `stack_grow_qemu_aarch64` (`plans/SPAWN.md` `SP11c`;
//! `docs/src/architecture/memory.md` §7c).
//!
//! Unlike the bespoke micro-kernel harnesses, every syscall and every user
//! fault here runs the production `KernelDispatchHook` /
//! `KernelSyscallHandlers` path: the chassis installs the hook through a
//! `DispatchCallbackSlot`, binds the production user-fault resolver to the
//! same slot (load *and* store/AMO U-mode page faults), wires the
//! production `LiveMemMap` producer (backing both `mem_map` and the
//! stack-growth fault path), a real `KernelProcessWait`, and a
//! `ProgramRegistry` carrying the three child roles, their numeric
//! parameters derived from the one shared `spawn_layout` policy. The
//! parent role is spawned through the production
//! `InitSpawnCtx::spawn_driver_process` seam; it spawns and reaps the
//! children through the production `spawn` + `wait` syscalls:
//!
//! * `grow` — recurses far past the eagerly committed stack top, verifying
//!   every frame's bytes survive the fault-driven growth, exits 0;
//! * `limit` — lowers its own `StackBytes` soft bound via `rlimit_set`,
//!   then recurses past it: the growth path refuses the bound and the
//!   kernel fault-kills it, exit 139;
//! * `guard` — reads the unmapped guard page below the reserved span:
//!   fault-killed, exit 139 (the structural defence stays).
//!
//! The chassis reaps the parent through the producer's non-blocking poll
//! and PASSes only on a parent exit of 0.

