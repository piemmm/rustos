//! The freestanding aarch64 test kernel: build one isolated EL0 program,
//! install a `MemMap` producer over its live address space, and route the
//! program's `mem_map`/`mem_unmap` syscalls through it (`plans/SPAWN.md`
//! `SP5b-2`).

