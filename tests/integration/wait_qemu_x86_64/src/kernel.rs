//! The x86_64 X4 test kernel: boot the production pipeline, then on
//! `BootCompleted` build a child and a parent ring-3 program, register their
//! parent/child link with a `KernelProcessWait` producer, and prove the parent
//! reaps the child's exit code under the live scheduler (`plans/PI.md` X4 —
//! the cross-port sibling of the aarch64 `wait_qemu_aarch64`).

