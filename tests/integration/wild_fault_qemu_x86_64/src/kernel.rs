//! The freestanding x86_64 test kernel: prove that a ring-3 exception the
//! kernel cannot resolve costs the faulting task and nothing else
//! (`plans/OPEN-DEFECTS.md` D42, D86), and that each kill's audit record
//! describes the cause it actually had (D87).
//!
//! The chassis runs the **shared production board bring-up**
//! (`tairix_kernel::x86_64::boot::bring_up_bsp`) — the exact per-CPU table /
//! exception-stub / `#PF` entry / NXE / LAPIC calibration / ACPI /
//! `syscall`+TSS / IO-APIC sequence the production `boot()` pipeline runs,
//! including the production syscall-dispatch callback, user-fault resolver
//! and user-fault terminator — and then installs the production
//! `KernelDispatchHook` into the production `DISPATCH_SLOT` those callbacks
//! already resolve through. Every syscall the programs issue and every
//! ring-3 fault therefore runs the production path.
//!
//! NXE matters here: the `#PF` error code's I/D bit is only set when
//! `IA32_EFER.NXE` is enabled (Intel SDM Vol 3A §4.7), so it is exactly the
//! production configuration in which a ring-3 instruction fetch escapes the
//! resolver's data-only gate — the D42 defect.
//!
//! The parent role is spawned through the production
//! `InitSpawnCtx::spawn_driver_process` seam; it spawns and reaps the three
//! faulting children through the production `spawn` + `wait` syscalls, and
//! the chassis PASSes only on a parent exit of 0 **and** three honestly
//! audited instruction-side kills ([`FaultAuditSink`]). The x86_64
//! `isa-debug-exit` device carries no per-site failure code, so every
//! failure site logs a distinct message (and the parent's diagnostic exit
//! code as a field) before flipping the failure exit.

