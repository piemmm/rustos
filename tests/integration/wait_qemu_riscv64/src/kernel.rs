//! The freestanding riscv64 RV-X4 test kernel: build a child and a parent
//! U-mode program, register their parent/child link with a `KernelProcessWait`
//! producer, and prove the parent reaps the child's exit code under the live
//! scheduler on the `virt` board (`plans/PI.md` RV-X4, the riscv64 sibling of
//! `wait_qemu_aarch64` / `_x86_64`).

