/// The single-core slice runs logical CPU 0 on the boot core.
const BOOT_CPU: CpuId = 0;

/// Gigabytes of identity map the EL0 address space provides: `[0, 2 GiB)`
/// covers the `virt` board's device MMIO (GiB 0 — including the virtio-MMIO
/// transports at [`GRANT_PHYS`]) and the RAM base at GiB 1 where this kernel
/// runs. [`USER_BIAS`] (64 GiB) and the device-window region sit far above.
const IDENTITY_GIB: usize = 2;

/// User stack base (1 MiB into the high user region) and size.
const USER_STACK_BASE: u64 = USER_BIAS + 0x10_0000;
/// User stack pages (256 KiB).
const USER_STACK_PAGES: u64 = 64;
/// User virtual address the startup-vector block is written at (3 MiB up).
const USER_BLOCK_BASE: u64 = USER_BIAS + 0x30_0000;

/// Base of the program's device-window virtual region: the retained
/// [`LiveSpace`]'s [`rustos_kernel_mem::MmioWindowMap`] hands the `mmio_map`
/// a guard-bracketed window out of this range. 1 GiB above [`USER_BIAS`] —
/// clear of the image, stack, and startup block — mirroring the production
/// aarch64 spawn layout (`init_spawn.rs`).
const MMIO_WINDOW_BASE: u64 = USER_BIAS + 0x4000_0000;
/// Pages backing the device-window region (256 KiB).
const MMIO_WINDOW_PAGES: usize = 64;

/// Base of the program's non-`FIXED` anonymous-heap virtual region: the
/// retained [`LiveSpace`]'s [`rustos_kernel_mem::AnonWindowMap`] places each
/// non-`FIXED` `mem_map` out of this range. 2 GiB above [`USER_BIAS`] —
/// above the device window and clear of the image/stack — mirroring the
/// production aarch64 spawn layout (`spawn_layout::ANON_WINDOW_OFFSET`).
const ANON_WINDOW_BASE: u64 = USER_BIAS + 0x8000_0000;
/// Pages backing the anonymous-heap window (this vertical maps only a couple
/// of pages out of it; the window is address space, backed on demand).
const ANON_WINDOW_PAGES: usize = 64;

/// Base of the program's guarded DMA-buffer virtual region: the retained
/// [`LiveSpace`]'s [`rustos_kernel_mem::DmaWindowMap`] carves each
/// `dma_alloc` buffer out of this range. 3 GiB above [`USER_BIAS`] — above
/// the anonymous-heap window and clear of the image/stack — mirroring the
/// production aarch64 spawn layout (`spawn_layout::DMA_WINDOW_OFFSET`).
const DMA_WINDOW_BASE: u64 = USER_BIAS + 0xC000_0000;
/// Pages backing the DMA-buffer window (256 KiB).
const DMA_WINDOW_PAGES: usize = 64;

/// Per-process stack-canary seed handed to the program (`AGENTS.md` §19.2).
const CANARY: u64 = 0x5520_C000_D15E_A5ED;

/// Physical frames the test hands the spawn build.
const FRAME_COUNT: usize = 128;

/// Cooperative-loop watchdog: maximum `step` iterations before the test
/// declares the workload deadlocked. Sized generously for QEMU TCG.
const MAX_STEPS: u64 = 5_000_000;

/// Stable audit-event ids for the QEMU transcript.
const TEST_START: EventId = EventId(4290);
const TEST_SPAWNED: EventId = EventId(4291);
const TEST_PASS: EventId = EventId(4292);
const TEST_FAIL: EventId = EventId(4293);
const TEST_MMIO_ENTER: EventId = EventId(4294);
const TEST_MMIO_MAPPED: EventId = EventId(4295);
const TEST_FAULT: EventId = EventId(4296);
const TEST_MEM_MAPPED: EventId = EventId(4297);
const TEST_MEM_UNMAPPED: EventId = EventId(4298);
const TEST_DMA_MAPPED: EventId = EventId(4299);

/// Failure finisher codes, distinct per failure site.
const FAIL_ZERO_FREQ: u16 = 1;
const FAIL_GIC: u16 = 2;
const FAIL_POOL: u16 = 3;
const FAIL_PARSE: u16 = 4;
const FAIL_BUILD: u16 = 5;
const FAIL_SCHED_NEW: u16 = 6;
const FAIL_SPAWN: u16 = 7;
const FAIL_DEADLOCK: u16 = 8;
const FAIL_UNEXPECTED_SYSCALL: u16 = 9;
const FAIL_LIVE_BUILD: u16 = 10;
const FAIL_DRAINED: u16 = 11;
const FAIL_FAULT_INSTALL: u16 = 12;
const FAIL_FAULT: u16 = 13;
/// Base finisher for an `exit` with a non-zero code (a program-side
/// verification failure); the program's exit code is added so the failing
/// site is identifiable.
const FAIL_EXIT_BASE: u16 = 100;

/// `true` once an `mmio_map` call returned a mapped base to the program.
static MAP_OK: AtomicBool = AtomicBool::new(false);

/// `true` once a non-`FIXED` `mem_map` round-trip (map → write → read-back →
/// `mem_unmap`) completed for the program — the placement-allocator proof
/// (`plans/PI.md` 5d-0-ii (c)). The program's `mem_unmap` sets it; PASS
/// requires both this and [`MAP_OK`].
static MEM_OK: AtomicBool = AtomicBool::new(false);

/// `true` once a `dma_alloc` carve returned a coherent buffer to the program
/// — the DMA-carve proof (`plans/PI.md` 5d-0-ii (c) DMA half). Set when the
/// dispatch services the program's `dma_alloc`; PASS requires it too.
static DMA_OK: AtomicBool = AtomicBool::new(false);

/// The device-resource grant handle the program carves its DMA buffer
/// against (the second grant the vertical mints for the task). Must match
/// the fixture program's `DMA_GRANT_HANDLE`.
const DMA_GRANT_HANDLE: u64 = 2;

/// Fault handler: any EL0 fault here is unexpected (the program only maps a
/// window and reads a register), so report it as a failure rather than hang
/// (`AGENTS.md` §7 / §2.9). The `esr`/`far` are logged so a diagnosing run can
/// tell a translation fault from an external abort.
extern "C" fn on_fault(esr: u64, far: u64, _elr: u64) -> ! {
    let mut esr_buf = [0u8; 16];
    let mut far_buf = [0u8; 16];
    log(
        &SERIAL_SINK,
        &Event {
            level: Level::Error,
            id: TEST_FAULT,
            message: "mmio_map test: unexpected EL0 fault",
            fields: &[
                rustos_log::Field {
                    key: "esr",
                    value: rustos_util::fmt::format_hex_u64(esr, &mut esr_buf),
                },
                rustos_log::Field {
                    key: "far",
                    value: rustos_util::fmt::format_hex_u64(far, &mut far_buf),
                },
            ],
        },
    );
    qemu_exit::exit_failure(FAIL_FAULT);
}

/// Size of the test's bump heap (startup block buffers + the user kthread's
/// kernel stack + control block + leaked allocator). Lives in `.bss`.
const HEAP_SIZE: usize = 2 * 1024 * 1024;

/// Page-aligned backing store for the bump heap.
#[repr(C, align(4096))]
struct HeapStore([u8; HEAP_SIZE]);

static mut HEAP: HeapStore = HeapStore([0; HEAP_SIZE]);

/// Global allocator backed by [`HEAP`].
///
/// SAFETY: the page-aligned `HEAP` static outlives the binary and the
/// allocator is its only consumer.
#[global_allocator]
static ALLOCATOR: FreeListAllocator =
    unsafe { FreeListAllocator::new(core::ptr::addr_of!(HEAP) as *mut u8, HEAP_SIZE) };

/// Page-table pool backing the EL0 address space (the image mappings, the
/// device-window tables the retained `LiveSpace` walks).
static PAGE_TABLES: PageTablePool = PageTablePool::new();

/// Physical-frame backing store the spawn builder draws user pages from.
/// `align(4096)` so each `PAGE_SIZE` slice is a valid page frame;
/// identity-mapped, so the builders reach it through [`DirectPhysMap::identity`].
#[repr(C, align(4096))]
struct FramePool([u8; paging::PAGE_SIZE * FRAME_COUNT]);

static mut FRAME_POOL: FramePool = FramePool([0; paging::PAGE_SIZE * FRAME_COUNT]);

/// Monotonic index of the next free [`FRAME_POOL`] frame.
static FRAME_CURSOR: core::sync::atomic::AtomicUsize = core::sync::atomic::AtomicUsize::new(0);

/// Hand out the next identity-mapped physical frame, or `None` when exhausted.
fn next_frame() -> Option<Frame> {
    let idx = FRAME_CURSOR.fetch_add(1, Ordering::SeqCst);
    if idx >= FRAME_COUNT {
        FRAME_CURSOR.store(FRAME_COUNT, Ordering::SeqCst);
        return None;
    }
    let offset = idx * paging::PAGE_SIZE;
    let base = core::ptr::addr_of!(FRAME_POOL) as u64 + offset as u64;
    Some(Frame::containing(PhysAddr::new(base)))
}

fn note(id: EventId, message: &'static str) {
    log(
        &SERIAL_SINK,
        &Event {
            level: Level::Info,
            id,
            message,
            fields: &[],
        },
    );
}

