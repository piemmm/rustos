/// A [`CapabilityQuery`] granting exactly `CAP_PROC_SPAWN` — the privilege the
/// spawn caller requires (`AGENTS.md` §5.4). It does not widen the program's
/// own authority (`AGENTS.md` §16.5).
struct SpawnAuthority;
impl CapabilityQuery for SpawnAuthority {
    fn holds(&self, cap: CapabilityId) -> bool {
        cap == CapabilityId::PROC_SPAWN
    }
}

/// Encode a `Result<u64, Errno>` into the syscall return register following the
/// `abi-v1` signed convention: a non-negative value on success, `-errno` on
/// error (the encoding `rustos_rt::mmio_map` decodes).
fn encode(result: Result<u64, Errno>) -> u64 {
    match result {
        Ok(value) => value,
        Err(err) => {
            let neg = -i64::from(err.as_i32());
            neg as u64
        }
    }
}

/// The syscall-dispatch callback the EL0 program's `svc` traps reach.
///
/// `mmio_map` is routed through the retained live space: the handle is
/// owner-checked (it must be the [`GRANT_HANDLE`] the boot path minted — the
/// registry-backed owner-check against the caller is host-proven in
/// `kernel/core`, `AGENTS.md` §5.4), then the granted window is mapped into the
/// program's *own* address space through [`with_current_live_space`] +
/// [`LiveSpace::map_device_window`] — the production retained-space mechanism
/// (`plans/PI.md` 5d-0-ii (b′)). An `exit` with code `0` is the program's PASS
/// signal (it mapped the window and read the device magic back); a non-zero
/// code is a program-side verification failure. Any other syscall is
/// unexpected and fails the test loudly (`AGENTS.md` §7).
extern "C" fn dispatch(number: u64, args_ptr: *const [u64; SYSCALL_MAX_ARGS]) -> u64 {
    // SAFETY: `args_ptr` points at the live `[u64; SYSCALL_MAX_ARGS]` the
    // exception handler built from the saved register frame; reading it for the
    // duration of this call is sound.
    let args = unsafe { &*args_ptr };
    #[allow(clippy::cast_possible_truncation)]
    let raw = number as u16;

    if raw == SyscallNumber::MMIO_MAP.as_u16() {
        note(TEST_MMIO_ENTER, "mmio_map test: dispatch handling mmio_map");
        let handle = args[0];
        // Owner-check the handle: only the minted grant resolves; any other
        // handle resolves to nothing and is refused (fail closed, §5.4 — the
        // registry-backed owner-check against the caller task is host-proven).
        if handle != GRANT_HANDLE {
            return encode(Err(Errno::NotFound));
        }
        // The program names a `[offset, offset + len)` sub-region of its
        // grant (`args[1]`/`args[2]`); confirm it lies wholly inside the
        // granted window before mapping, mirroring the production kernel
        // `mappable_subwindow` check (`AGENTS.md` §24.1 / §5.4 — a driver maps
        // only inside a region it was granted).
        let offset = args[1];
        let sub_len = args[2];
        let in_bounds = sub_len != 0
            && offset
                .checked_add(sub_len)
                .is_some_and(|end| end <= GRANT_LEN);
        if !in_bounds {
            return encode(Err(Errno::OutOfRange));
        }
        // Map only the requested sub-region into the program's own retained
        // live space: the producer reads the current CPU's published live
        // space and maps that region, caching disabled, never executable
        // (§18.3 / §19.2). No published space (a task admitted without one)
        // fails closed.
        let result = match with_current_live_space(BOOT_CPU, |space| {
            #[allow(clippy::cast_possible_truncation)]
            space.map_device_window(GRANT_PHYS + offset, sub_len as usize)
        }) {
            Some(Ok(va)) => Ok(va),
            Some(Err(_)) => Err(Errno::BadAddress),
            None => Err(Errno::NotImplemented),
        };
        if result.is_ok() {
            MAP_OK.store(true, Ordering::SeqCst);
            note(TEST_MMIO_MAPPED, "mmio_map test: granted window mapped");
        }
        encode(result)
    } else if raw == SyscallNumber::MEM_MAP.as_u16() {
        // Non-`FIXED` `mem_map`: the program asks the kernel to place the
        // region, so route to the retained live space's placement allocator
        // (`plans/PI.md` 5d-0-ii (c)) — the production `LiveMemMap` non-`FIXED`
        // path. `args[0]` is the byte length; the flags/hint are ignored here
        // (the fixture only issues non-`FIXED` requests).
        let len = args[0] as usize;
        let result = match page_count_for(len) {
            Ok(pages) => {
                match with_current_live_space(BOOT_CPU, |space| space.map_anonymous_placed(pages)) {
                    Some(Ok(base)) => {
                        note(TEST_MEM_MAPPED, "mem_map test: placed anonymous region");
                        Ok(base)
                    }
                    Some(Err(_)) => Err(Errno::OutOfMemory),
                    None => Err(Errno::NotImplemented),
                }
            }
            Err(_) => Err(Errno::LengthOutOfRange),
        };
        encode(result)
    } else if raw == SyscallNumber::MEM_UNMAP.as_u16() {
        // Release the placed region. `args[0]` is the base, `args[1]` the byte
        // length. The placement record is validated + released inside
        // `unmap_anonymous` (fail closed on a wrong base/extent, §5.4).
        let base = args[0];
        let len = args[1] as usize;
        let result = match page_count_for(len) {
            Ok(pages) => {
                match with_current_live_space(BOOT_CPU, |space| space.unmap_anonymous(base, pages))
                {
                    Some(Ok(())) => {
                        MEM_OK.store(true, Ordering::SeqCst);
                        note(TEST_MEM_UNMAPPED, "mem_map test: placed region released");
                        Ok(0)
                    }
                    Some(Err(_)) => Err(Errno::NotFound),
                    None => Err(Errno::NotImplemented),
                }
            }
            Err(_) => Err(Errno::LengthOutOfRange),
        };
        encode(result)
    } else if raw == SyscallNumber::DMA_ALLOC.as_u16() {
        // Carve a coherent DMA buffer into the program's retained live space
        // via the production `LiveSpace::alloc_dma` (`plans/PI.md` 5d-0-ii (c)
        // DMA half). The registry-backed grant owner-check is host-proven in
        // kernel/core; this stand-in accepts only the minted DMA handle and
        // fails closed otherwise (§5.4). The device-visible-base copy-out is
        // host-proven, so this returns only the CPU VA. `args[0]` is the grant
        // handle, `args[1]` the byte length; no addressing limit is declared
        // for the `virt` coherent stand-in.
        if args[0] != DMA_GRANT_HANDLE {
            return encode(Err(Errno::NotFound));
        }
        let len = args[1] as usize;
        let result = match with_current_live_space(BOOT_CPU, |space| space.alloc_dma(len, 0)) {
            Some(Ok(mapping)) => {
                DMA_OK.store(true, Ordering::SeqCst);
                note(
                    TEST_DMA_MAPPED,
                    "dma_alloc test: coherent DMA buffer carved",
                );
                Ok(mapping.cpu_va)
            }
            Some(Err(_)) => Err(Errno::OutOfMemory),
            None => Err(Errno::NotImplemented),
        };
        encode(result)
    } else if raw == SyscallNumber::EXIT.as_u16() {
        #[allow(clippy::cast_possible_truncation)]
        let code = args[0] as u16;
        if code == 0
            && MAP_OK.load(Ordering::SeqCst)
            && MEM_OK.load(Ordering::SeqCst)
            && DMA_OK.load(Ordering::SeqCst)
        {
            note(
                TEST_PASS,
                "mmio_map test: EL0 mapped the granted window, read the device magic, round-tripped a placed mem_map, and carved a coherent dma_alloc buffer",
            );
            qemu_exit::exit_success();
        }
        note(
            TEST_FAIL,
            "mmio_map test: program exited with a failure code",
        );
        qemu_exit::exit_failure(FAIL_EXIT_BASE + code);
    } else {
        note(
            TEST_FAIL,
            "mmio_map test: fixture issued an unexpected syscall",
        );
        qemu_exit::exit_failure(FAIL_UNEXPECTED_SYSCALL);
    }
}

/// A `'static` frame allocator over a dedicated window, supplied to the
/// retained [`LiveSpace`] for anonymous-map frames. The non-`FIXED`
/// `mem_map` round-trip the program performs draws its couple of pages from
/// here (the `mmio_map` device-window path draws page tables from the arch
/// space's own pool instead), so the pool only needs a handful of frames.
const ANON_POOL_PAGES: usize = 16;

#[repr(C, align(4096))]
struct AnonPool([u8; paging::PAGE_SIZE * ANON_POOL_PAGES]);

static mut ANON_POOL: AnonPool = AnonPool([0; paging::PAGE_SIZE * ANON_POOL_PAGES]);

/// Build a leaked `'static` [`FrameAllocator`] over [`ANON_POOL`].
fn leaked_anon_frames() -> &'static FrameAllocator {
    let base = core::ptr::addr_of!(ANON_POOL) as u64;
    let mut map = BootMemoryMap::new();
    map.push(MemoryRegion {
        kind: RegionKind::Usable,
        start: PhysAddr::new(base),
        length: (paging::PAGE_SIZE * ANON_POOL_PAGES) as u64,
    });
    let alloc = FrameAllocator::new(&map).expect("anon pool builds an allocator");
    Box::leak(Box::new(alloc))
}

/// Boot entry point — the symbol the arch crate's `boot.s` trampoline calls
/// (via `rustos_arch_aarch64_main`).
#[no_mangle]
pub extern "C" fn kernel_main(_dtb: u64) -> ! {
    note(TEST_START, "aarch64 mmio_map test: starting");

    // Enable FP/SIMD at EL1 before any code that may use it (the `rxe` decoder
    // and the image fills compile to NEON `memcpy`/`memcmp`).
    // SAFETY: this is the boot CPU, called once, before any FP/SIMD executes.
    unsafe { enable_fp_el1() };

    // P3/P4: discover the board from the embedded `virt` device tree.
    let Ok(fdt) = Fdt::new(DTB_BLOB) else {
        qemu_exit::exit_failure(FAIL_GIC);
    };
    let counter_hz = timer_frequency_hz(&fdt);
    if counter_hz == 0 {
        qemu_exit::exit_failure(FAIL_ZERO_FREQ);
    }
    if gic::configure_from_fdt(&fdt).is_none() {
        qemu_exit::exit_failure(FAIL_GIC);
    }

    // Parse the build-time `rxe` blob against the kernel's own CFI tag.
    let Ok(image) = rustos_abi::rxe::LoadImage::parse(PROGRAM_RXE, &SYSCALL_TABLE_HASH) else {
        qemu_exit::exit_failure(FAIL_PARSE);
    };

    // Build the EL0 address space and activate it (so the user mappings, and
    // later the device window, land in the active translation regime).
    let Some(arch) = ArchAddressSpace::new_identity_gigapages(&PAGE_TABLES, IDENTITY_GIB) else {
        qemu_exit::exit_failure(FAIL_POOL);
    };
    let root_phys = arch.root_phys();
    // SAFETY: the identity map covers the kernel's current `pc`, `sp`, heap,
    // frame pool, and device MMIO (all within `[0, 2 GiB)` on `virt`), so
    // switching it does not move the ground under the running code. Boot CPU.
    unsafe { arch.switch() };

    let mut space = AddressSpace::new(arch);
    let physmap = DirectPhysMap::identity((IDENTITY_GIB as u64) << 30);
    let request = SpawnRequest {
        image: &image,
        image_bytes: PROGRAM_RXE,
        bias: USER_BIAS,
        stack: UserStack {
            base: USER_STACK_BASE,
            page_count: USER_STACK_PAGES,
        },
        start_block_base: USER_BLOCK_BASE,
        args: &[b"mmio-map"],
        env: &[],
        canary: CANARY,
    };

    // SAFETY: building the image is itself safe; the returned `UserEntry` is
    // only entered later, once the space is reactivated (via `pre_resume`) and
    // the trap path is installed. Frames are drawn from `FRAME_POOL`.
    let entry = match unsafe {
        spawn_image(
            &SpawnAuthority,
            &SERIAL_SINK,
            &mut space,
            &physmap,
            &request,
            next_frame,
        )
    } {
        Ok(entry) => entry,
        Err(_) => qemu_exit::exit_failure(FAIL_BUILD),
    };

    // Retain the *same* arch space live behind the production `LiveSpace`, so
    // the program's `mmio_map` and non-`FIXED` `mem_map` mutate exactly the
    // active address space (`plans/PI.md` 5d-0-ii (b′)/(c)). The device-window
    // region sits 1 GiB above the image bias and the anonymous-heap window
    // 2 GiB above; the anonymous frame allocator backs the placed `mem_map`.
    let Ok(live) = LiveSpace::new(
        space,
        DirectPhysMap::identity((IDENTITY_GIB as u64) << 30),
        leaked_anon_frames(),
        VirtAddr::new(MMIO_WINDOW_BASE),
        MMIO_WINDOW_PAGES,
        VirtAddr::new(ANON_WINDOW_BASE),
        ANON_WINDOW_PAGES,
        VirtAddr::new(DMA_WINDOW_BASE),
        DMA_WINDOW_PAGES,
    ) else {
        qemu_exit::exit_failure(FAIL_LIVE_BUILD);
    };
    let live: Box<dyn LiveUserSpace + Send> = Box::new(live);

    // Bring up the EL1 vectors + GICv2 and install the dispatch callback so the
    // program's `svc`s are handled. Interrupts stay masked — the cooperative
    // `step` loop is the only scheduling mechanism.
    // SAFETY: called once on the boot CPU with a stack established and the MMU
    // enabled (the address-space build switched it on).
    unsafe {
        exceptions::init_vectors();
        gic::init();
    }
    syscall_entry::set_dispatch_callback(dispatch);
    if fault::set_fault_handler(on_fault).is_err() {
        qemu_exit::exit_failure(FAIL_FAULT_INSTALL);
    }

    // Build the live scheduler over the arch port.
    static ARCH_STORAGE: rustos_arch_aarch64::Aarch64ArchStorage<1> =
        rustos_arch_aarch64::Aarch64ArchStorage::new();
    let arch = Arc::new(rustos_arch_aarch64::Aarch64Arch::new(
        &ARCH_STORAGE,
        BOOT_CPU,
        counter_hz,
    ));
    let Ok(sched) = Scheduler::new(SchedulerConfig::defaults_for(1), arch) else {
        qemu_exit::exit_failure(FAIL_SCHED_NEW);
    };

    // Admit the EL0 program as a resumable user kthread that **retains** the
    // live space (`spawn_user_kthread_with_stack_live`, the production aarch64
    // spawn path): its `pre_resume` hook reactivates its page-table root before
    // every switch-in (isolation, §4), the runtime publishes the retained space
    // on the per-CPU live-space slot while it runs, and its work body
    // `enter_user`s into EL0.
    let cs = ContextSwitchHal::new();
    let user_mode = UserMode::new();
    let pre_resume = move |_stack_top: u64| {
        // SAFETY: the MMU is enabled and `root_phys` is the L1 root of a space
        // that identity-maps the low kernel window — `activate_user_root`'s
        // contract.
        unsafe { activate_user_root(root_phys) };
    };
    let work = move |_yielder: &mut Yielder<ContextSwitchHal>| {
        // SAFETY: the entered space is active (the `pre_resume` hook just
        // reactivated it) and the EL1 trap vector + dispatch callback are
        // installed, so the program's `svc`s are handled.
        unsafe { user_mode.enter_user(entry) }
    };
    if spawn_user_kthread_with_stack_live(
        &sched,
        cs,
        BoxStack::new(),
        BOOT_CPU,
        Priority::Normal,
        pre_resume,
        live,
        work,
    )
    .is_err()
    {
        qemu_exit::exit_failure(FAIL_SPAWN);
    }
    note(TEST_SPAWNED, "aarch64 mmio_map test: EL0 program spawned");

    // Drive `step` until the program runs. The program exits (0 on success)
    // through the dispatch callback, which finishes the run; a program that
    // drained without exiting, or a never-draining loop, fails loud
    // (`AGENTS.md` §7).
    let mut steps = 0u64;
    while sched.live_task_count() != 0 && steps < MAX_STEPS {
        let _ = sched.step(BOOT_CPU);
        steps += 1;
    }

    if steps >= MAX_STEPS {
        qemu_exit::exit_failure(FAIL_DEADLOCK);
    }
    // The program always exits through the dispatch callback (which finishes
    // the run); reaching here means it drained without exiting.
    qemu_exit::exit_failure(FAIL_DRAINED);
}
