//! The freestanding aarch64 test kernel for the FIX-IO IO2 block-transport
//! fault vertical (`plans/FIX-IO.md` IO2).
//!
//! Every syscall the fixture issues runs the production `KernelDispatchHook`
//! / `KernelSyscallHandlers` path: the chassis brings the `virt` board up,
//! leaks the live subsystems, installs the production hook through a
//! `DispatchCallbackSlot`, and spawns the fixture through the production
//! `InitSpawnCtx::spawn_driver_process` seam. So the ticketed call endpoint,
//! the per-request deadline, the reply wait-set, and the reap/cancel paths the
//! fixture exercises are all the shipped kernel objects, not a bespoke shim.
//!
//! Two chassis-specific pieces earn their place here:
//!
//! * **the wait-queue arch adapter**, so a parked waiter is genuinely unparked
//!   by its wake event rather than by a fail-safe no-op; and
//! * **the timed-wake sweep in the drive loop**, standing in for the timer
//!   interrupt a production port takes. The fixture's whole point is a request
//!   that fails closed at an elapsed deadline, and nothing else in a chassis
//!   would ever notice that deadline pass.
//!
//! The chassis reaps the fixture and PASSes only on exit 0; any other exit
//! becomes a finisher code naming the fixture's own failing step.

