//! The x86_64 P-1c test kernel: boot the production pipeline, then on
//! `BootCompleted` build one isolated ring-3 spinner and prove the production
//! LAPIC-timer IRQ involuntarily preempts it (`plans/PI.md` D2b-2b-A P-1c).

extern crate alloc;

