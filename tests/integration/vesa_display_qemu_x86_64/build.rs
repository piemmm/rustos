//! Build script for the Stage 4 vesa-display (x86_64) QEMU vertical.
//!
//! Two jobs, both done on the host where the toolchain and
//! `ed25519-dalek` are available:
//!
//! 1. Hand the x86_64 kernel linker script (which carries the multiboot
//!    header) to `rustc` on the freestanding `x86_64-unknown-none`
//!    target — the single per-arch linker script the architecture port
//!    owns, shared by every x86_64 freestanding QEMU test
//!    (`AGENTS.md` §2.2).
//! 2. Sign a synthetic vesa-driver `.rxe` manifest requesting exactly
//!    [`CapabilityId::DRV_LOAD`] with a deterministic test seed, and emit
//!    a Rust source file the bin pulls in via `include!`.
//!
//! The manifest requests only `CAP_DRV_LOAD`:
//! `rustos_drv_display_vesa::register` gates on it, and the host installs
//! the manifest's requested set intersected with the caller's grants
//! (`AGENTS.md` §5.2). The `CAP_MMIO_MAP` the surface mapping
//! additionally requires is granted on the separate `DriverHost` the bin
//! builds for `VesaFramebuffer::open`, never through the manifest,
//! mirroring how the framebuffer and bus-driver verticals separate the
//! load gate from the map gate.
//!
//! Re-running `build.rs` produces byte-identical output for the same
//! seed; the test is therefore deterministic (`AGENTS.md` §7).

use ed25519_dalek::{Signer, SigningKey};
use rustos_abi::{CapabilityId, DriverKind, DriverManifest, DRIVER_MANIFEST_MAGIC};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// Deterministic signing seed so the trust anchor is stable across
/// builds. Distinct from the other QEMU fixtures' seeds so the images
/// cannot be confused. The bytes spell `"vesadisplay…"`.
const TEST_SEED: [u8; 32] = [
    0x76, 0x65, 0x73, 0x61, 0x64, 0x69, 0x73, 0x70, 0x6c, 0x61, 0x79, 0x27, 0xb4, 0x6d, 0x32, 0xe9,
    0x58, 0xac, 0x41, 0x7f, 0xd3, 0x22, 0x99, 0x60, 0x3b, 0xc7, 0x1e, 0x84, 0xfa, 0x51, 0x2d, 0x66,
];

/// SHA-256 fingerprint of the host's syscall table. The concrete value
/// is irrelevant; both sides feed the same value into the `HostConfig`.
const SYS_HASH: [u8; 32] = [0x22; 32];

fn main() {
    rustos_itest_harness::emit_target_cfg();
    println!("cargo:rerun-if-changed=build.rs");

    let target = std::env::var("TARGET").unwrap_or_default();
    if target == "x86_64-unknown-none" {
        let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
        let linker_script = format!(
            "{}/../../../kernel/arch/x86_64/linker.ld",
            manifest_dir.trim_end_matches('/')
        );
        println!("cargo:rerun-if-changed={linker_script}");
        println!("cargo:rustc-link-arg=-T{linker_script}");
    }

    let signing_key = SigningKey::from_bytes(&TEST_SEED);
    let signer_pubkey: [u8; 32] = signing_key.verifying_key().to_bytes();

    // The vesa driver's `register` entry checks `CAP_DRV_LOAD`. The
    // effective set is the intersection of the loading user's grants and
    // this manifest request, so name it here as well as on the caller.
    let caps: &[u16] = &[CapabilityId::DRV_LOAD.as_u16()];
    let mut manifest = DriverManifest {
        magic: DRIVER_MANIFEST_MAGIC,
        abi_version: rustos_abi::ABI_VERSION_CURRENT,
        kind: DriverKind::UserSpace,
        bind_key_count: 0,
        capability_count: u16::try_from(caps.len()).expect("caps fit in u16"),
        syscall_table_hash: SYS_HASH,
        signer_pubkey,
        signature: [0u8; 64],
    };
    let encoded = manifest.to_le_bytes();
    let mut signed_message = Vec::with_capacity(DriverManifest::WIRE_LEN - 64 + caps.len() * 2);
    signed_message.extend_from_slice(&encoded[..DriverManifest::WIRE_LEN - 64]);
    for c in caps {
        signed_message.extend_from_slice(&c.to_le_bytes());
    }
    let sig = signing_key.sign(&signed_message);
    manifest.signature = sig.to_bytes();

    let mut image: Vec<u8> = Vec::new();
    image.extend_from_slice(&manifest.to_le_bytes());
    for c in caps {
        image.extend_from_slice(&c.to_le_bytes());
    }

    let mut out = String::new();
    out.push_str("// Auto-generated by build.rs. DO NOT EDIT.\n");
    out.push_str("/// Signed vesa-driver `.rxe` image bytes.\n");
    out.push_str("pub const VESA_IMAGE: &[u8] = &[");
    for (i, b) in image.iter().enumerate() {
        if i % 16 == 0 {
            out.push_str("\n    ");
        }
        write!(out, "0x{b:02x}, ").expect("write to String never fails");
    }
    out.push_str("\n];\n\n");
    out.push_str("/// Trust-anchor public key the host's `HostConfig` accepts.\n");
    out.push_str("pub const TRUSTED_SIGNER_PUBKEY: [u8; 32] = [");
    for (i, b) in signer_pubkey.iter().enumerate() {
        if i % 8 == 0 {
            out.push_str("\n    ");
        }
        write!(out, "0x{b:02x}, ").expect("write to String never fails");
    }
    out.push_str("\n];\n\n");
    out.push_str("/// SHA-256 fingerprint of the host's syscall table.\n");
    out.push_str("pub const SYSCALL_TABLE_HASH: [u8; 32] = [");
    for (i, b) in SYS_HASH.iter().enumerate() {
        if i % 8 == 0 {
            out.push_str("\n    ");
        }
        write!(out, "0x{b:02x}, ").expect("write to String never fails");
    }
    out.push_str("\n];\n");

    let out_dir = env::var_os("OUT_DIR").expect("OUT_DIR set by cargo");
    let path = PathBuf::from(out_dir).join("vesa_fixture.rs");
    fs::write(&path, out).expect("write vesa_fixture.rs");
}
