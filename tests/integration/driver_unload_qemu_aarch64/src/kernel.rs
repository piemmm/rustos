//! The freestanding aarch64 test kernel: spawn a driver through the
//! production devmgr-driven spawn path, then tear it down through the
//! production driver-unload mechanism and assert every kernel-held piece of
//! it was reclaimed (`plans/USB.md` U1).
//!
//! The build script compiles the pure-Rust driver-stub fixture
//! (`tests/integration/driver_register_program`) position-independent and
//! wraps it as the signed payload of a `kind = UserSpace` driver image,
//! exactly as the driver-spawn vertical does. On boot the test discovers the
//! `virt` board, enables the identity MMU + EL1 vectors, builds the live
//! kernel registries, and autoloads the stub through the production
//! `DeviceManager::autoload` + `SpawnDriverLoader` +
//! `InitCtxDriverProcessSpawn` over the `Aarch64ProcessSpawn` image builder —
//! the driver is admitted as a parked **loading** task with its placeholder
//! capability record minted (its address space is built on the driver's own
//! first slice, which this teardown test never runs).
//!
//! It then drives the symmetric partner of the spawn seam,
//! `InitSpawnCtx::terminate_driver_process` (the mechanism the driver-store
//! server runs for `StoreRequest::Unload`), and asserts the driver task was
//! reaped (the scheduler's live-task count drops 1 → 0) and its capability
//! record and address-space entry reclaimed. A second unload of the now-gone
//! handle must fail closed with `NotFound` (the teardown is idempotent).
//! PASS once teardown reclaimed everything and the idempotent miss was
//! observed; any shortfall writes a distinct failure finisher (fail-loud).

