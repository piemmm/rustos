//! The freestanding riscv64 test kernel: spawn one runaway U-mode spinner and
//! prove the production supervisor-timer interrupt involuntarily preempts it
//! (`plans/PI.md` D2b-2b-A P-1b, the riscv64 sibling of
//! `preempt_el0_qemu_aarch64`).

