//! The freestanding aarch64 test kernel: prove the per-service account
//! ceiling binds a lying manifest end to end (`plans/USERS.md` U4).
//!
//! Every syscall here runs the production `KernelDispatchHook` /
//! `KernelSyscallHandlers` path: the chassis installs the hook through a
//! `DispatchCallbackSlot`, wires the **real compiled system identity table**
//! (`tairix_kernel_core::system_identity_table`) into the spawn-as-user
//! seam, seeds the hardware tree backing `hw_tree_read`, and registers the
//! `svc` role under a manifest that requests devmgr's ceiling plus every
//! sibling service's defining capability. The parent role is spawned
//! through the production `InitSpawnCtx::spawn_driver_process` seam with
//! `CAP_PROC_SPAWN` + `CAP_SPAWN_AS_USER`; it switches `svc` into the
//! devmgr account through the production `spawn` syscall and propagates its
//! verdict. The chassis reaps the parent and PASSes only on exit 0.

