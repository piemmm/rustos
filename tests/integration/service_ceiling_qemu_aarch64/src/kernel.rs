/// The single-core slice runs logical CPU 0 on the boot core.
const BOOT_CPU: CpuId = 0;

/// Gigabytes of identity map the boot address space provides: `[0, 2 GiB)`
/// covers the `virt` board's device MMIO (GiB 0) and the RAM base at GiB 1
/// where this kernel, its heap, and the frame pool live.
const IDENTITY_GIB: usize = 2;

/// Physical frames the production spawn producer draws from: two spawned
/// processes (image, eagerly committed stack top, page tables,
/// identity-window tables) with generous headroom (16 MiB).
const FRAME_COUNT: usize = 4096;

/// Longest decimal argument the rows below need (`u32::MAX` is 10 digits).
const DEC_MAX: usize = 10;

/// Render `value` as a fixed-width, zero-padded decimal byte string at
/// compile time. Leading zeroes are harmless: the fixture's parser accepts
/// them, and a fixed width lets the argument live in a `static` the
/// registry row borrows.
const fn dec_bytes(mut value: u32) -> [u8; DEC_MAX] {
    let mut out = [b'0'; DEC_MAX];
    let mut i = DEC_MAX;
    while i > 0 {
        i -= 1;
        out[i] = b'0' + (value % 10) as u8;
        value /= 10;
        if value == 0 {
            break;
        }
    }
    out
}

/// The devmgr service uid as a decimal argument-vector value — resolved
/// from the one compiled account set, never a copied constant.
static DEVMGR_UID_ARG: [u8; DEC_MAX] = dec_bytes(tairix_users::DEVMGR_UID.0);

/// The sibling services' defining capabilities the `svc` manifest lies
/// about: login's spawn-as-user + users-read pair, seatmgr's seat
/// administration, and sysinfod's privileged introspection primitive.
const SIBLING_CAPS: [CapabilityId; 4] = [
    CapabilityId::SPAWN_AS_USER,
    CapabilityId::USERS_READ,
    CapabilityId::SEAT_ADMIN,
    CapabilityId::SYSINFO_INTROSPECT,
];

/// The `svc` row's manifest length: devmgr's whole ceiling plus the
/// sibling capabilities above.
const SVC_MANIFEST_LEN: usize = tairix_users::DEVMGR_CEILING.len() + SIBLING_CAPS.len();

/// Concatenate devmgr's ceiling and [`SIBLING_CAPS`] at compile time, so
/// the lying manifest imports the one ceiling definition rather than
/// copying its members.
const fn svc_manifest() -> [CapabilityId; SVC_MANIFEST_LEN] {
    let mut out = [SIBLING_CAPS[0]; SVC_MANIFEST_LEN];
    let mut i = 0;
    while i < tairix_users::DEVMGR_CEILING.len() {
        out[i] = tairix_users::DEVMGR_CEILING[i];
        i += 1;
    }
    let mut j = 0;
    while j < SIBLING_CAPS.len() {
        out[i + j] = SIBLING_CAPS[j];
        j += 1;
    }
    out
}

/// The `svc` role's deliberately over-wide manifest request.
static SVC_MANIFEST: [CapabilityId; SVC_MANIFEST_LEN] = svc_manifest();

