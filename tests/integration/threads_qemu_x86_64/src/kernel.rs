/// The single-core slice runs logical CPU 0 on the boot processor.
const BOOT_CPU: u32 = 0;

/// Physical frames the production spawn producer and the demand-fault path
/// draw from: six spawned processes (image, eagerly committed stack top, page
/// tables) plus each role's threads — every thread costs one eagerly backed
/// stack page, a kernel stack, and whatever its body faults in. Sized from
/// that appetite with generous headroom (16 MiB).
const FRAME_COUNT: usize = 4096;

/// Threads the `counter` role runs. Four is enough for genuine contention on
/// the shared counter's futex mutex while staying comfortably inside the
/// frame pool below.
const COUNTER_THREADS: u64 = 4;

/// Increments each `counter` thread performs. Large enough that an
/// unsynchronised increment would almost certainly lose an update, so a
/// correct total is real evidence the lock works.
const COUNTER_INCREMENTS: u64 = 250;

/// Threads the `tls` role runs, each with its own thread-local block.
const TLS_THREADS: u64 = 3;

/// Worker threads the `parallel` role's pool asks the kernel for. Three beside
/// the dispatching thread, so the fork-join barrier genuinely waits for several
/// acknowledgements while staying inside the frame pool below.
const PARALLEL_WORKERS: u64 = 3;

/// Rounds the `parallel` role runs its divided pass for. Enough repetitions that
/// a lost wake or a mis-claimed piece cannot pass by luck; the pass itself is
/// small.
const PARALLEL_ROUNDS: u64 = 32;

/// The status the `groupexit` role ends its process with. Named once here and
/// threaded into *both* the `groupexit` row (the code it exits with) and the
/// `parent` row (the code it must observe), so the two cannot drift.
const GROUP_EXIT_CODE: u64 = 41;

/// Longest decimal argument the rows below need (`u64::MAX` is 20 digits).
const DEC_MAX: usize = 20;

/// Render `value` as a fixed-width, zero-padded decimal byte string at
/// compile time. Leading zeroes are harmless: the fixture's parser accepts
/// them, and a fixed width lets the argument live in a `static` the
/// registry row borrows.
const fn dec_bytes(mut value: u64) -> [u8; DEC_MAX] {
    let mut out = [b'0'; DEC_MAX];
    let mut i = DEC_MAX;
    while i > 0 {
        i -= 1;
        out[i] = b'0' + (value % 10) as u8;
        value /= 10;
        if value == 0 {
            break;
        }
    }
    out
}

/// [`COUNTER_THREADS`] as a decimal argument-vector value.
static COUNTER_THREADS_ARG: [u8; DEC_MAX] = dec_bytes(COUNTER_THREADS);
/// [`COUNTER_INCREMENTS`] as a decimal argument-vector value.
static COUNTER_INCREMENTS_ARG: [u8; DEC_MAX] = dec_bytes(COUNTER_INCREMENTS);
/// [`TLS_THREADS`] as a decimal argument-vector value.
static TLS_THREADS_ARG: [u8; DEC_MAX] = dec_bytes(TLS_THREADS);
/// [`PARALLEL_WORKERS`] as a decimal argument-vector value.
static PARALLEL_WORKERS_ARG: [u8; DEC_MAX] = dec_bytes(PARALLEL_WORKERS);
/// [`PARALLEL_ROUNDS`] as a decimal argument-vector value.
static PARALLEL_ROUNDS_ARG: [u8; DEC_MAX] = dec_bytes(PARALLEL_ROUNDS);
/// [`GROUP_EXIT_CODE`] as a decimal argument-vector value.
static GROUP_EXIT_CODE_ARG: [u8; DEC_MAX] = dec_bytes(GROUP_EXIT_CODE);

/// Cooperative-loop watchdog: maximum `step` iterations before the test
/// declares the workload deadlocked. Sized generously for QEMU TCG.
const MAX_STEPS: u64 = 5_000_000;

/// Stable audit-event ids for the QEMU transcript.
const TEST_START: EventId = EventId(4498);
const TEST_SPAWNED: EventId = EventId(4499);
const TEST_PASS: EventId = EventId(4500);
/// Every failure site logs through this id with a distinct message (the
/// x86_64 `isa-debug-exit` device carries no per-site exit code).
const TEST_FAIL: EventId = EventId(4501);

/// Static heap for the free-list allocator (per the production bin); the
/// chassis subsystems, the spawn producer's boxed state, and the demand-
/// grown bookkeeping allocate from it.
static mut HEAP: Heap = Heap::ZERO;

/// Global allocator backed by [`HEAP`].
///
/// SAFETY: the page-aligned `HEAP` static outlives the binary and the
/// allocator is its only consumer.
#[global_allocator]
static ALLOCATOR: FreeListAllocator =
    unsafe { FreeListAllocator::new(core::ptr::addr_of!(HEAP) as *mut u8, HEAP_BYTES) };

/// Physical-frame backing store the live [`FrameAllocator`] serves the
/// spawn producer and the stack-growth fault path from. `align(4096)` so
/// each `PAGE_SIZE` slice is a valid page frame. A higher-half kernel
/// static, so its physical address is its virtual address minus
/// [`KERNEL_VMA_BASE`] — inside the low identity window the producer's
/// page-table walk and each child's own root require.
#[repr(C, align(4096))]
struct FramePool([u8; PAGE_SIZE * FRAME_COUNT]);

static mut FRAME_POOL: FramePool = FramePool([0; PAGE_SIZE * FRAME_COUNT]);

/// Per-CPU storage backing the scheduler's arch handle.
static SCHED_ARCH_STORAGE: X86_64ArchStorage<1> = X86_64ArchStorage::new();

/// Per-CPU storage backing the dispatch hook + spawn ctx arch handle.
static HOOK_ARCH_STORAGE: X86_64ArchStorage<1> = X86_64ArchStorage::new();

/// This vertical binds no IRQ lines; the fail-closed controller mirrors
/// what `kernel/core::init` installs when a port exposes no routing.
static IRQ_CONTROLLER: UnsupportedController = UnsupportedController;

fn note(id: EventId, message: &'static str) {
    log(
        &SERIAL_SINK,
        &Event {
            level: Level::Info,
            id,
            message,
            fields: &[],
        },
    );
}

/// Log the failure site and flip the QEMU failure exit. The
/// `isa-debug-exit` device carries no per-site code, so the message is the
/// site identifier the transcript preserves.
fn fail(message: &'static str) -> ! {
    log(
        &SERIAL_SINK,
        &Event {
            level: Level::Error,
            id: TEST_FAIL,
            message,
            fields: &[],
        },
    );
    qemu_exit::exit_failure()
}

