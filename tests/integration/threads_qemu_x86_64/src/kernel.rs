//! The freestanding x86_64 test kernel: prove lightweight threads end to
//! end (`plans/THREADS.md` `T3b-u`; `docs/src/architecture/threads.md`).
//!
//! Every syscall and every user fault here runs the production
//! `KernelDispatchHook` / `KernelSyscallHandlers` path — the shared production board bring-up
//! (`tairix_kernel::x86_64::boot::bring_up_bsp`) installs the production
//! dispatch callback and user-fault resolver, and this chassis fills the
//! production `DISPATCH_SLOT` they resolve through, over the
//! production `LiveMemMap` producer (the `tairix-rt` heap and the
//! demand-backed thread stacks), a real `KernelProcessWait`, and a real
//! `KernelProcessSignal` — which threads genuinely need: a group `exit` has to
//! drive every sibling to its stopping point, and the process teardown lands
//! only once the last of them is down. The parent role of the fixture program
//! (`tests/integration/threads_program`) is spawned through the production
//! `InitSpawnCtx::spawn_driver_process` seam; it spawns and reaps each child
//! role through the production `spawn` + `wait` syscalls:
//!
//! * `counter` — N threads over one address space each increment a shared
//!   counter under a futex `Mutex`, and each is joined for its own tally, so
//!   both the shared heap and the kernel's clear-on-exit wake are proven;
//! * `rendezvous` — a `Condvar` wait that only completes because it genuinely
//!   *parked*: on this single-CPU cooperative drive a spinning wait would
//!   starve the very thread that has to notify it;
//! * `tls` — each thread reads its own magic through its psABI thread pointer,
//!   before and after a trap, so the register is proven per-thread;
//! * `exitearly` — a thread that ends itself with `thread_exit` releases its
//!   joiner (through the kernel's word, not a store of its own) and reports
//!   that it produced no value;
//! * `parallel` — a real `lib/parallel` worker pool runs a divided pass many
//!   times and every round matches the same pass run on one thread, proving the
//!   fork-join protocol on real threads: the epoch wake, the claim, the barrier
//!   over workers, the erased dispatch pointer's lifetime, nested dispatch, and
//!   the join at drop.
//! * `groupexit` — a sibling parked in the kernel on a condition variable
//!   nobody notifies, then `exit(code)`: the process is reapable only because
//!   the group exit reached that parked thread.
//!
//! The chassis reaps the parent through the wait producer's non-blocking poll
//! and PASSes only on a parent exit of 0.

