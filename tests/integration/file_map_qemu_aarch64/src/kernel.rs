//! The freestanding aarch64 test kernel: prove the **production**
//! demand-paged file-mapping path end to end (`plans/APPS.md` M1 remainder;
//! `docs/src/architecture/memory.md` §7o).
//!
//! Unlike the bespoke micro-kernel harnesses, every syscall and every user
//! fault here runs the production `KernelDispatchHook` /
//! `KernelSyscallHandlers` path: the chassis installs the hook through a
//! `DispatchCallbackSlot`, binds the production user-fault resolver to the
//! same slot, wires the production `LiveMemMap` producer (both `mem_map`
//! and `file_map`), a read-only in-guest filesystem double serving one
//! fixture file, a real `KernelProcessWait`, and a `ProgramRegistry`
//! carrying the three child roles. The parent role is spawned through the
//! production `InitSpawnCtx::spawn_driver_process` seam; it spawns and
//! reaps the children through the production `spawn` + `wait` syscalls:
//!
//! * `verify` — demand-faults first/interior/EOF-straddle pages,
//!   read-verifies the fixture bytes and the zero fill, proves the mapping
//!   survives `fs_close`, hands an **untouched** mapped page to `fs_open`
//!   (the copy-path fault-resolution proof), unmaps, exits 0;
//! * `wild` — maps, unmaps, then reads the unmapped base: fault-killed,
//!   exit 139;
//! * `store` — maps, faults a page resident, stores to it: the read-only
//!   write-fault gate kills it, exit 139.
//!
//! The chassis reaps the parent through the producer's non-blocking poll
//! and PASSes only on a parent exit of 0.

