/// The single-hart slice runs logical CPU 0 on the boot hart.
const BOOT_CPU: CpuId = 0;

/// Physical frames the production spawn producer and the demand-fault path
/// draw from: six spawned processes (image, eagerly committed stack top, page
/// tables) plus each role's threads — every thread costs one eagerly backed
/// stack page, a kernel stack, and whatever its body faults in. Sized from
/// that appetite with generous headroom (16 MiB).
const FRAME_COUNT: usize = 4096;

/// Threads the `counter` role runs. Four is enough for genuine contention on
/// the shared counter's futex mutex while staying comfortably inside the
/// frame pool below.
const COUNTER_THREADS: u64 = 4;

/// Increments each `counter` thread performs. Large enough that an
/// unsynchronised increment would almost certainly lose an update, so a
/// correct total is real evidence the lock works.
const COUNTER_INCREMENTS: u64 = 250;

/// Threads the `tls` role runs, each with its own thread-local block.
const TLS_THREADS: u64 = 3;

/// Worker threads the `parallel` role's pool asks the kernel for. Three beside
/// the dispatching thread, so the fork-join barrier genuinely waits for several
/// acknowledgements while staying inside the frame pool below.
const PARALLEL_WORKERS: u64 = 3;

/// Rounds the `parallel` role runs its divided pass for. Enough repetitions that
/// a lost wake or a mis-claimed piece cannot pass by luck; the pass itself is
/// small.
const PARALLEL_ROUNDS: u64 = 32;

/// The status the `groupexit` role ends its process with. Named once here and
/// threaded into *both* the `groupexit` row (the code it exits with) and the
/// `parent` row (the code it must observe), so the two cannot drift.
const GROUP_EXIT_CODE: u64 = 41;

/// Longest decimal argument the rows below need (`u64::MAX` is 20 digits).
const DEC_MAX: usize = 20;

/// Render `value` as a fixed-width, zero-padded decimal byte string at
/// compile time. Leading zeroes are harmless: the fixture's parser accepts
/// them, and a fixed width lets the argument live in a `static` the
/// registry row borrows.
const fn dec_bytes(mut value: u64) -> [u8; DEC_MAX] {
    let mut out = [b'0'; DEC_MAX];
    let mut i = DEC_MAX;
    while i > 0 {
        i -= 1;
        out[i] = b'0' + (value % 10) as u8;
        value /= 10;
        if value == 0 {
            break;
        }
    }
    out
}

