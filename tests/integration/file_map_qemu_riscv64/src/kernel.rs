/// Forward to the shared riscv64 panic bridge (parks the hart; the run then
/// times out and the harness reports the failure).
#[panic_handler]
fn file_map_qemu_riscv64_panic(info: &PanicInfo<'_>) -> ! {
    handle_panic_via_serial(info)
}

/// The syscall-dispatch callback every program's `ecall` traps reach. It
/// mirrors the production bin-crate callback (`dispatch_riscv64`): read the
/// kernel-stack args frame and forward through the resident production
/// [`KernelDispatchHook`] via the shared `dispatch_via_slot` bridge. An
/// empty slot or a missing caller context fails the test loudly.
extern "C" fn dispatch(number: u64, args_ptr: *const [u64; SYSCALL_MAX_ARGS]) -> u64 {
    // SAFETY: the trap trampoline lays the frame out on the kernel
    // stack and only invokes us with a valid pointer; the array lives at
    // least until we return.
    let args = unsafe { read_raw_args(args_ptr) };
    match dispatch_via_slot(&DISPATCH_SLOT, number, args) {
        Some(value) => value,
        None => qemu_exit::exit_failure(FAIL_NO_DISPATCH),
    }
}

/// The user-fault resolver the S-mode trap path calls for every U-mode
/// load/store page fault: the exact production glue
/// (`production_user_fault`), bound to this vertical's own slot so a load
/// fault runs the resident production hook's `resolve_file_fault` path and
/// a store (or unresolvable load) kills the faulting task through the
/// production fault-exit path.
extern "C" fn file_map_user_fault(stval: u64, write: bool) -> bool {
    resolve_user_fault_via_slot(&DISPATCH_SLOT, stval, write)
}

/// The in-guest read-only filesystem double: serves exactly the one
/// fixture file the shared definition emits, under the caller-blind
/// `FilesystemService` seam the production handlers consume. Everything
/// else fails closed — a mutation is `PermissionDenied` (the double is
/// read-only), an unknown path is `NotFound`, and the surfaces this
/// vertical never exercises are `NotImplemented` (an inert interface
/// announces itself, mirroring `NullFilesystemService`).
struct FixtureFs;

impl FilesystemService for FixtureFs {
    fn open(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        path: &str,
        flags: OpenFlags,
    ) -> Result<(), Errno> {
        if path != FIXTURE_PATH {
            return Err(Errno::NotFound);
        }
        if flags.is_write() {
            return Err(Errno::PermissionDenied);
        }
        Ok(())
    }

    fn read(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        path: &str,
        offset: u64,
        buf: &mut [u8],
    ) -> Result<usize, Errno> {
        if path != FIXTURE_PATH {
            return Err(Errno::NotFound);
        }
        let len = FIXTURE_CONTENT.len() as u64;
        if offset >= len {
            return Ok(0);
        }
        let available = usize::try_from(len - offset).map_err(|_| Errno::OutOfRange)?;
        let n = buf.len().min(available);
        let start = usize::try_from(offset).map_err(|_| Errno::OutOfRange)?;
        buf[..n].copy_from_slice(&FIXTURE_CONTENT[start..start + n]);
        Ok(n)
    }

    fn write(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
        _offset: u64,
        _append: bool,
        _data: &[u8],
    ) -> Result<usize, Errno> {
        Err(Errno::PermissionDenied)
    }

    fn readdir(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
    ) -> Result<Vec<ReaddirEntry>, Errno> {
        Err(Errno::NotImplemented)
    }

    fn stat(&self, _uid: u32, _caps: &dyn CapabilityQuery, path: &str) -> Result<FileStat, Errno> {
        if path != FIXTURE_PATH {
            return Err(Errno::NotFound);
        }
        let len = FIXTURE_CONTENT.len() as u64;
        Ok(FileStat {
            kind: FileKind::Regular,
            size: len,
            allocated: len,
            mode: 0o444,
            uid: 0,
            gid: 0,
        })
    }

    fn truncate(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
        _size: u64,
    ) -> Result<(), Errno> {
        Err(Errno::PermissionDenied)
    }

    fn sync(&self, _uid: u32, _caps: &dyn CapabilityQuery) -> Result<(), Errno> {
        Err(Errno::NotImplemented)
    }

    fn mkdir(&self, _uid: u32, _caps: &dyn CapabilityQuery, _path: &str) -> Result<(), Errno> {
        Err(Errno::PermissionDenied)
    }

    fn unlink(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
        _flags: UnlinkFlags,
    ) -> Result<(), Errno> {
        Err(Errno::PermissionDenied)
    }

    fn rename(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _from: &str,
        _to: &str,
    ) -> Result<(), Errno> {
        Err(Errno::PermissionDenied)
    }

    fn set_mode(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
        _mode: u32,
    ) -> Result<(), Errno> {
        Err(Errno::PermissionDenied)
    }

    // The fixture stores no extended attributes; every attribute call
    // answers the typed unsupported-backing refusal.
    fn attr_get(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
        _key: &[u8],
        _value_out: &mut [u8],
    ) -> Result<usize, Errno> {
        Err(Errno::NotSupported)
    }

    fn attr_set(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
        _key: &[u8],
        _value: &[u8],
    ) -> Result<(), Errno> {
        Err(Errno::NotSupported)
    }

    fn attr_list(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
        _index: u64,
        _key_out: &mut [u8],
    ) -> Result<Option<usize>, Errno> {
        Err(Errno::NotSupported)
    }

    fn attr_remove(
        &self,
        _uid: u32,
        _caps: &dyn CapabilityQuery,
        _path: &str,
        _key: &[u8],
    ) -> Result<(), Errno> {
        Err(Errno::NotSupported)
    }
}

/// The single installed filesystem double.
static FIXTURE_FS: FixtureFs = FixtureFs;

/// The wait-queue arch adapter over the live scheduler + arch handle — the
/// chassis twin of the boot path's adapter — so `PROCWAIT_WAITQ` wakes (a
/// child's `exit` unparking the parent blocked in the production `wait`)
/// reach the live scheduler. Without it every wake is a fail-safe no-op
/// and the parent parks forever.
struct ChassisWaitArch {
    scheduler: &'static Scheduler<RiscvBinArch>,
    arch: &'static RiscvBinArch,
}

impl rustos_kernel_core::waitq::WaitQueueArch for ChassisWaitArch {
    fn unpark(&self, id: rustos_kernel_sched_api::TaskId) {
        // Cancellation-safe: an unpark racing the park records a
        // wake-pending token, so a wake is never lost.
        let _ = self.scheduler.unpark(id);
    }

    fn now_ns(&self) -> u64 {
        KernelArch::monotonic_ns(self.arch, SchedulerArch::current_cpu(self.arch))
    }

    fn set_wakeup(&self, deadline_ns: Option<u64>) {
        SchedulerArch::set_wakeup(self.arch, deadline_ns);
    }

    fn current_task(
        &self,
        cpu: rustos_kernel_sched_api::CpuId,
    ) -> Option<rustos_kernel_sched_api::TaskId> {
        self.scheduler.current_task(cpu)
    }

    fn current_cpu(&self) -> Option<rustos_kernel_sched_api::CpuId> {
        Some(SchedulerArch::current_cpu(self.arch))
    }
}

/// The capability set the fixture programs run under: `FS_ACCESS` for the
/// children's `fs_open`/`file_map`, and `PROC_SPAWN` for the parent's
/// `spawn`. The parent's set doubles as the inherited ceiling the
/// production spawn intersects each child's manifest request with, so a
/// child's effective set is exactly its registry row's request.
fn parent_caps() -> CapabilitySet {
    let mut caps = CapabilitySet::empty();
    caps.insert(CapabilityId::PROC_SPAWN);
    caps.insert(CapabilityId::FS_ACCESS);
    caps
}

/// The child roles' manifest capability request: file access only — a
/// child spawns nothing.
static CHILD_CAPS: &[CapabilityId] = &[CapabilityId::FS_ACCESS];

