/// Leak a zeroed `&'static [AtomicU64]` of `count` slots for the arch
/// handle's per-CPU bookkeeping, alive for the kernel's lifetime like
/// the leaked console grids.
fn leak_u64_slots(count: usize) -> Option<&'static [AtomicU64]> {
    let mut slots = Vec::new();
    slots.try_reserve_exact(count).ok()?;
    slots.resize_with(count, || AtomicU64::new(0));
    Some(Box::leak(slots.into_boxed_slice()))
}

/// Leak a zeroed `&'static [AtomicU8]` of `count` slots (the per-CPU
/// core-class table).
fn leak_u8_slots(count: usize) -> Option<&'static [AtomicU8]> {
    let mut slots = Vec::new();
    slots.try_reserve_exact(count).ok()?;
    slots.resize_with(count, || AtomicU8::new(0));
    Some(Box::leak(slots.into_boxed_slice()))
}

/// Build the [`Aarch64Arch`] handle over leaked per-CPU slices sized
/// exactly to the validated dense CPU map.
///
/// `cpu_mpidrs` comes from [`crate::cpu_topology::order_cpus`], which
/// guarantees a non-empty list with the running boot core at dense id
/// 0 — the only ways `with_cpu_slices` can refuse are therefore
/// programmer errors, on which the boot parks fail-closed with a serial
/// beacon rather than continuing over per-CPU state of the wrong shape.
fn build_arch_handle(cpu_mpidrs: &[u64], counter_hz: u64) -> Aarch64Arch {
    let count = cpu_mpidrs.len();
    let Some(cpu_to_mpidr) = leak_u64_slots(count) else {
        serial::beacon("pi-boot: CPU affinity slots allocation FAILED, parking");
        halt_current_cpu()
    };
    let Some(host_ipi_count) = leak_u64_slots(count) else {
        serial::beacon("pi-boot: IPI counter slots allocation FAILED, parking");
        halt_current_cpu()
    };
    let Some(core_classes) = leak_u8_slots(count) else {
        serial::beacon("pi-boot: core-class slots allocation FAILED, parking");
        halt_current_cpu()
    };
    Aarch64Arch::with_cpu_slices(
        cpu_to_mpidr,
        host_ipi_count,
        core_classes,
        BOOT_CPU,
        counter_hz,
        cpu_mpidrs,
    )
    .unwrap_or_else(|| {
        serial::beacon("pi-boot: arch handle construction FAILED, parking");
        halt_current_cpu()
    })
}

/// Leak a zeroed secondary-stack region of `count` slots (one per dense
/// CPU id; slot 0 belongs to the never-started boot CPU).
///
/// Zeroed in place in the heap — never built on the boot stack, whose
/// budget a 64 KiB-per-slot array would blow — and leaked for the kernel's
/// lifetime, exactly as the `smp.s` trampoline requires. An out-of-memory
/// boot heap parks fail-closed: without stacks no secondary may ever be
/// started.
fn leak_zeroed_secondary_stacks(count: usize) -> &'static [smp::SecondaryStack] {
    // Reserving as `Vec<SecondaryStack>` makes the block's 16-byte stack
    // alignment a property of the allocation itself rather than of a
    // byte-pointer cast, and keeps the out-of-memory path a value.
    let mut stacks: Vec<smp::SecondaryStack> = Vec::new();
    if stacks.try_reserve_exact(count).is_err() {
        serial::beacon("pi-boot: secondary stack allocation FAILED, parking");
        halt_current_cpu()
    }
    let spare = stacks.spare_capacity_mut();
    let spare_bytes = core::mem::size_of_val(spare);
    let spare_start = spare.as_mut_ptr().cast::<u8>();
    // SAFETY: `spare_start`/`spare_bytes` describe exactly `stacks`' own
    // uninitialised capacity, which the reservation above made at least
    // `count` slots long; all-zero is a valid `SecondaryStack` (a plain byte
    // array), so writing zeros over it initialises every slot `set_len`
    // then exposes. Zeroing in place never materialises a 64 KiB value on
    // the boot stack, whose budget that would blow.
    unsafe {
        core::ptr::write_bytes(spare_start, 0, spare_bytes);
        stacks.set_len(count);
    }
    // Leaked, not boxed: the `smp.s` trampoline reads the region with the
    // MMU off for the kernel's lifetime, and leaking the reservation as-is
    // avoids a shrink-to-fit copy of the whole stack pool.
    Vec::leak(stacks)
}

/// Stage the multi-core bring-up: size and publish the secondary stack
/// region, publish the dense-id → affinity table (the identity source a
/// spin-table-released core recovers its dense id from), and install
/// the production secondary entry, so the starts `kernel_main` issues
/// later — PSCI `CPU_ON` or spin-table release — find everything in
/// place.
///
/// `cpu_mpidrs` is the validated dense map from
/// [`crate::cpu_topology::order_cpus`] (entry `i` is dense id `i`'s
/// affinity). Returns `true` when the machine is ready to start
/// secondaries (or is single-CPU, where there is nothing to prepare).
/// Every install is set-once per boot and this is their only production
/// call site, so a refusal is a programmer error; it is reported
/// (`false` → the boot line's `smp_prepared` field) and every later
/// start fails closed and audited rather than releasing a core into a
/// half-published hand-off.
fn prepare_secondary_bringup(cpu_mpidrs: &[u64]) -> bool {
    let cpu_count = cpu_mpidrs.len();
    if cpu_count <= 1 {
        return true;
    }
    let stacks = leak_zeroed_secondary_stacks(cpu_count);
    if smp::register_secondary_stacks(stacks).is_err() {
        return false;
    }
    let mut affinities = Vec::new();
    if affinities.try_reserve_exact(cpu_count).is_err() {
        return false;
    }
    affinities.extend_from_slice(cpu_mpidrs);
    let affinities: &'static [u64] = Box::leak(affinities.into_boxed_slice());
    if smp::register_secondary_affinities(affinities).is_err() {
        return false;
    }
    smp::set_secondary_entry(production_secondary_entry).is_ok()
}

/// Discover each CPU's CoreSight external-debug component base from the
/// firmware tree and install the per-CPU registry the lockup watchdog's
/// cross-core PC sampler reads ([`tairix_arch_aarch64::coresight`]).
///
/// Runs post-MMU (it walks the whole tree) with the dense `cpu_mpidrs` map
/// and the device-gigapage mask already resolved. A discovered base is
/// installed **only** when its window sits in an already-Device-mapped
/// gigapage, so a read on the lockup path can never fault; a component in
/// an unmapped gigapage — or a tree that describes no debug components
/// (QEMU `virt`, the stock Pi 4 firmware DTB) — installs nothing, and the
/// sampler reports `Unsupported` (fail closed, the buddy detector runs
/// unchanged). Allocation failure or a table with no reachable component is
/// a silent no-op — a diagnostic aid never aborts the boot.
#[cfg(feature = "watchdog-diagnostics")]
fn install_debug_component_bases(fdt: &Fdt<'_>, cpu_mpidrs: &[u64]) {
    use tairix_arch_aarch64::coresight;
    use tairix_arch_aarch64::paging::{device_gigapages, gigapage_is_device};

    let mut bases = Vec::new();
    if bases.try_reserve_exact(cpu_mpidrs.len()).is_err() {
        return;
    }
    bases.resize(cpu_mpidrs.len(), coresight::NO_BASE);
    fdt::debug_component_bases(fdt, cpu_mpidrs, &mut bases);

    // Only keep a base whose gigapage is already Device-typed in the live
    // identity map; a component elsewhere is dropped rather than read
    // through an unmapped (or Normal, cacheable) window.
    let mask = device_gigapages();
    for base in &mut bases {
        if *base == coresight::NO_BASE {
            continue;
        }
        let gigapage = *base >> 30;
        if !gigapage_is_device(&mask, gigapage) {
            *base = coresight::NO_BASE;
        }
    }

    if bases.iter().any(|&b| b != coresight::NO_BASE) {
        let bases: &'static [usize] = Box::leak(bases.into_boxed_slice());
        coresight::install_debug_bases(bases);
    }
}

/// The entry every started secondary core runs (via the `smp.s`
/// trampoline): per-CPU hardware init, then join the live kernel's
/// dispatch loop.
///
/// Ordering is load-bearing:
///
/// 1. FP/SIMD on, before any code the compiler may lower to NEON.
/// 2. Adopt the boot identity map — the very first memory-system act,
///    while this core has performed no atomic read-modify-write (LDXR/
///    STXR exclusives are unreliable on MMU-off Device-typed DRAM).
/// 3. EL1 vectors + GICv2 CPU interface + per-CPU preemption/IPI arming
///    — each banked or per-core state that must be programmed on the
///    core that uses it.
/// 4. [`tairix_kernel_core::run_secondary`], which audits the arrival
///    and dispatches until the kernel stops.
///
/// The kernel-core hand-off was published before this core's `CPU_ON`
/// was issued, so a refusal from `run_secondary` is a genuine fault; it
/// is reported on the UART debug line and the core parks fail-closed.
extern "C" fn production_secondary_entry(cpu: u32) -> ! {
    // SAFETY: this secondary core's first action, exactly once, before
    // any FP/SIMD instruction executes on it.
    unsafe {
        enable_fp_el1();
    }
    // SAFETY: the trampoline hands over MMU-off with all interrupts
    // masked and this core has touched no exclusives yet; the boot CPU
    // published the park root before any `CPU_ON` (it enabled its own
    // MMU during `boot`), so the adopted tables are live and coherent.
    if !unsafe { tairix_arch_aarch64::paging::adopt_boot_translation() } {
        // No published boot root: nothing sane to run on — park.
        halt_current_cpu()
    }
    // SAFETY: per-CPU installs on this core, exactly once each, before
    // any interrupt source is armed here: the EL1 vector base and the
    // GICv2 CPU interface are banked per core (the distributor write in
    // `gic::init` idempotently re-enables what the boot CPU enabled).
    unsafe {
        exceptions::init_vectors();
        gic::init();
    }
    // Per-CPU tickless preemption + IPI arming (the callbacks and the
    // per-CPU backing were installed by the boot CPU before `CPU_ON`).
    crate::aarch64::gic_irq::init_secondary_preemption(cpu);

    // Join the live kernel. Returns only when this core must stop.
    let exit = tairix_kernel_core::run_secondary(cpu);
    log(
        &SERIAL_SINK,
        &Event {
            level: Level::Warn,
            id: KERNEL_SECONDARY_PARKED,
            message: "aarch64: secondary cpu left the dispatch loop; parking",
            fields: &[Field {
                key: "cause",
                value: tairix_log::FieldValue::Str(exit.as_str()),
            }],
        },
    );
    halt_current_cpu()
}

/// Resolve and audit which discovered storage node binds the bootstrap
/// root block driver.
///
/// Read-only: it walks the firmware tree (safe with the MMU **on** — the
/// caller enables it first; a whole-tree traversal faults MMU-off,
/// `plans/PI.md` watch-out), resolves each node against the in-kernel
/// bootstrap-floor catalogue, and audits the decision through `log_sink`.
/// It mounts nothing; the production mount path ([`crate::root_mount`])
/// consumes the binding in the following increment. A null/unreadable
/// tree, a malformed walk, or no block device simply leaves the root
/// unbound — never aborting the boot.
///
/// `video` carries the framebuffer boot console's discovered scan-out
/// facts when one came up; the surface is published into the same
/// buffered tree as the boot display node (`plans/DISPLAY.md` D7d), so
/// the user-space display service autoloads against it. `None` (a
/// UART-only boot) publishes no display node.
fn audit_root_storage_binding(
    dtb: u64,
    video: Option<video::DiscoveredVideo>,
    log_sink: &'static (dyn Sink + Sync),
) {
    if dtb == 0 {
        return;
    }
    // SAFETY: on the boot hand-off `dtb` is the firmware/loader device-tree
    // pointer (`boot.s` preserves x0). `Fdt::from_ptr` validates the magic
    // and bounds the blob by its own `totalsize` before any further read.
    // The full-tree discovery walk below runs with the MMU on (the caller
    // enabled it), where a whole-tree traversal is safe; a bogus pointer
    // fails the magic check and returns `Err` rather than faulting.
    let Ok(fdt) = (unsafe { Fdt::from_ptr(dtb as *const u8) }) else {
        return;
    };
    // The validated blob's own length, captured before the walk consumes
    // the reader, so the virtio-MMIO probe below can reborrow the same
    // firmware bytes the bus builder needs.
    let total = fdt.total_size();
    let mut sink = crate::boot_hwtree::CollectingHwNodeSink::new();
    if platform::FdtDiscovery::new(fdt)
        .discover(&mut sink)
        .is_err()
    {
        // A malformed tree is not fatal: leave the root unbound — the mount
        // path fails closed without a binding.
        return;
    }

    // Bootstrap-floor virtio-MMIO bus enumeration: the raw `virtio,mmio` nodes the discovery walk emitted carry
    // only their `compatible` string, which binds no block driver — the
    // virtio-blk bind key is the device id read from the transport. Probe
    // each slot's `DeviceID` through the MMIO bus driver and emit a probed
    // virtio-block child node into the same buffered tree so the gate can
    // bind the root *and* the kthread's autoload sees a faithful tree. The
    // Raspberry Pi 4 tree describes no `virtio,mmio` node, so
    // `virtio_mmio_bus_from_dtb` returns `NotFound` and this is a no-op there
    // — it is the QEMU `virt`-board path, additive and metal-neutral.
    // SAFETY: `dtb`/`total` bound the firmware blob `Fdt::from_ptr` validated
    // above; it is identity-mapped and immutable for the kernel's life, and
    // the virtio-MMIO aperture it describes is identity-mapped Device memory
    // the probe alone reads (side-effect-free `DeviceID` registers, MMU on —
    // the caller enabled it, so this whole-tree walk is safe, `plans/PI.md`).
    let dtb_bytes = unsafe { core::slice::from_raw_parts(dtb as *const u8, total) };
    let probe = unsafe { tairix_drv_bus_mmio::virtio_mmio_bus_from_dtb(dtb_bytes) };
    if let Ok(bus) = probe {
        // A bus enumeration error (an over-full or malformed bus) leaves the
        // root unbound rather than aborting the boot.
        let _ = crate::hwdiscovery::observe_virtio_mmio_block_devices(&bus, &mut sink);
        // Bootstrap-floor virtio-MMIO input discovery: probe each slot's `DeviceID` for a virtio-input device and
        // emit a user-space-autoloadable `Input` node carrying its register
        // window as a grant request into the same buffered tree, so the
        // unlock kthread's `devmgr` autoload spawns the matching user-space
        // input driver with exactly that window (`plans/PI.md` P10 5d-2-ii).
        // The two reads of `bus` are sequential, so the immutable borrows do
        // not overlap. A no-op on the Pi tree (no `virtio,mmio` node), so it
        // is metal-neutral and additive. An enumeration
        // error leaves the input nodes undiscovered, never aborting the boot.
        // Resolve each virtio-input slot's GICv2 INTID from the firmware tree
        // (`device_spi` decodes the node's `interrupts` specifier — a
        // discovered value, never a board constant) so the emitted node carries the IRQ line its interrupt-driven
        // user-space driver parks on.
        let _ = crate::hwdiscovery::observe_virtio_mmio_input_devices(
            &bus,
            &|slot_base| {
                // Re-parse the validated blob per slot: the first `fdt` was
                // consumed by the discovery walk above, and there are only a
                // handful of virtio-input slots, so re-reading the FDT header
                // is negligible boot-time cost. A bogus
                // pointer fails the magic check and yields `None`, skipping
                // the slot fail-closed.
                // SAFETY: `dtb`/`total` bound the firmware blob `Fdt::from_ptr`
                // validated above; it is identity-mapped and immutable for the
                // kernel's life, and the MMU is on (the caller enabled it).
                let fdt = unsafe { Fdt::from_ptr(dtb as *const u8) }.ok()?;
                crate::aarch64::root_unlock::device_spi(&fdt, slot_base)
            },
            &mut sink,
            log_sink,
        );
        // Bootstrap-floor virtio-MMIO network discovery (`plans/NETWORK.md`
        // N4e-β): the exact sibling of the input probe above — probe each
        // slot's `DeviceID` for a virtio-net device and emit a
        // user-space-autoloadable `Network` node carrying its register
        // window, DMA constraint, and discovered GICv2 interrupt line, so
        // the autoload path spawns the matching user-space virtio-net driver
        // process (which then serves the `netchan` channel to `netstack`).
        // The IRQ line is resolved by the same per-slot `device_spi` decode
        // (a discovered value, never a board constant); a sequential
        // immutable read of `bus`, a no-op on the Pi tree, and fail-closed on
        // any enumeration error, exactly like the input probe.
        let _ = crate::hwdiscovery::observe_virtio_mmio_network_devices(
            &bus,
            &|slot_base| {
                // SAFETY: as the input probe's closure above — `dtb` bounds
                // the firmware blob validated at boot, identity-mapped and
                // immutable for the kernel's life, MMU on.
                let fdt = unsafe { Fdt::from_ptr(dtb as *const u8) }.ok()?;
                crate::aarch64::root_unlock::device_spi(&fdt, slot_base)
            },
            &mut sink,
            log_sink,
        );
    }

    // Publish the framebuffer boot console's scan-out surface as the boot
    // display node (`plans/DISPLAY.md` D7d), into the same buffered tree the
    // block and input probes feed, so the pre-unlock autoload matches the
    // user-space display service against it. A degenerate mode is skipped
    // fail-closed inside the observer, and the collecting sink never fills,
    // so the emit cannot fail — the discard mirrors the observers above.
    if let Some(video) = video {
        let _ = crate::boot_display::observe_boot_display(
            &crate::boot_display::BootScanout {
                base: video.fb_base,
                width_px: video.width_px,
                height_px: video.height_px,
                stride_bytes: video.stride_bytes,
                format: video.format,
                memory: video.memory,
            },
            &mut sink,
        );
    }

    // Leak the buffered tree to `'static` (a one-shot boot publish, like the
    // leaked `KernelState` — never a mutable global) so the
    // unlock kthread can match every discovered node against the signed
    // driver store during autoload. The tree
    // outlives the boot frame and lives for the running kernel's lifetime.
    let tree: &'static [HwNode] = sink.leak();

    // Resolve + audit the root binding from the same buffered tree, then
    // stash both (with the firmware DTB pointer) for the init seam, where the
    // in-kernel root-unlock kthread reads it once (`plans/PI.md` P11 Chunk
    // B-2 INCREMENT (2)). The MMU is on here (the caller enabled it), so the
    // `SpinLock` stash's atomic read-modify-write is well-defined — the same
    // post-MMU constraint the keyboard discovery stash carries. A `None`
    // binding (no/ambiguous disk) leaves the unlock a no-op and `login` fails
    // closed; the tree is still stashed so an input driver can still
    // autoload on a diskless boot once a store is reachable.
    let binding = crate::root_storage::resolve_root_block_driver(tree, log_sink);
    crate::unlock_service::record_boot(binding, dtb, tree);
}

/// The two memory figures the hand-off carries, which discovery produces
/// together and only [`BootInfo`] consumes: the physical map the frame
/// allocator is built from, and the platform's installed total *before* the
/// identity map's Device clip drops the bytes it cannot reach.
struct BootMemory {
    map: tairix_kernel_mem::BootMemoryMap,
    installed_bytes: u64,
}

/// Assemble the validated [`BootInfo`] hand-off and enter
/// [`tairix_kernel_core::kernel_main`].
///
/// Installs the production `svc` dispatch callback before user space can
/// be entered (the `kernel_core` `Syscall` phase publishes the resident
/// hook into [`DISPATCH_SLOT`]), wraps the validated [`Aarch64Arch`] in
/// the local [`Aarch64BinArch`] `KernelArch`, and installs the discovered
/// console list: with the framebuffer boot console active the video
/// console is the only console and the UART stays the session-free debug
/// log line (`plans/PI.md` P11); otherwise the UART is the only console.
/// A hand-off that `BootInfo::validate` rejects parks fail-closed rather
/// than entering the core.
fn enter_kernel_core(
    arch: Aarch64Arch,
    memory: BootMemory,
    heap: &'static tairix_kalloc::FreeListAllocator,
    log_sink: &'static (dyn Sink + Sync),
    audit_sink: &'static (dyn Sink + Sync),
    log_level: Level,
    hw_tree: &'static (dyn tairix_kernel_core::HwTreeSource + 'static),
) -> ! {
    // The arch port's `svc` trampoline fail-closes if it fires before a
    // callback is installed, so install it before any user thread runs.
    // No user space exists yet at P6c-2; pinning it here keeps the
    // ordering identical to the x86_64 boot path.
    syscall_entry::set_dispatch_callback(production_dispatch);
    // Demand-paged file mappings resolve their EL0 data aborts through the
    // same resident hook; install the resolver beside the dispatch callback
    // so both are in place before user space exists. This single-entry boot
    // path installs exactly once; a second publish would be a programmer
    // error, so it parks fail-closed rather than running with an
    // unpredictable fault path.
    if tairix_arch_aarch64::fault::set_user_fault_resolver(production_user_fault).is_err() {
        tairix_arch_aarch64::kernel_arch::halt_current_cpu();
    }
    // Beside the resolver, install the terminator the trap handler uses for
    // an EL0 exception it cannot resolve (an illegal instruction, an
    // alignment fault): it kills the offending task and keeps the CPU alive,
    // so one task's bad instruction can never park a core. Installed once,
    // before user space; a second publish is a programmer error that parks
    // fail-closed rather than running with an unpredictable fault path.
    if tairix_arch_aarch64::fault::set_user_fault_terminator(production_user_fault_terminate)
        .is_err()
    {
        tairix_arch_aarch64::kernel_arch::halt_current_cpu();
    }

    // The discovered dense CPU count sizes the scheduler's run queues
    // and names how many cores `kernel_main`'s SMP phase brings online.
    let cpu_count = arch.cpu_count();
    // Recover the firmware power-control conduit the boot path discovered
    // from the `/psci` node (the same method the secondary-core bring-up
    // uses) so the Supervisor's `reboot`/`poweroff` can drive PSCI
    // `SYSTEM_RESET` / `SYSTEM_OFF` through it. A tree with no `/psci` node
    // (spin-table bring-up) leaves it `None`, so both fail safe (unsupported).
    let psci_method = match arch.secondary_start() {
        Some(SecondaryStart::Psci(method)) => Some(method),
        _ => None,
    };
    let arch = Arc::new(Aarch64BinArch::new(arch).with_psci_method(psci_method));
    // Publish the arch handle for the panic-handler bridge before it is
    // moved into `BootInfo` (a panic after this point carries registers +
    // a backtrace; before it, the pre-init serial path runs).
    // SAFETY: `arch` is moved into `BootInfo` immediately below (which
    // `kernel_main` consumes and stores); `Arc::as_ptr` is stable for the
    // lifetime of any clone of the `Arc`.
    unsafe {
        crate::aarch64::panic_ctx::publish_arch(Arc::as_ptr(&arch));
    }
    // One decision for the console list and the seat registry, so the seat's
    // text sink, the console whose display surface its lease hands over, and
    // the console a descriptor's index names cannot disagree.
    let (consoles, seat_registry) = console_layout();
    let boot_info = BootInfo::new(
        BOOT_CPU,
        cpu_count,
        "",
        memory.map,
        SchedulerConfig::defaults_for(cpu_count),
        arch,
        log_sink,
        audit_sink,
        log_level,
        &DISPATCH_SLOT,
        heap,
    )
    // Install the discovered console list (`plans/PI.md` P11): when the
    // P7b framebuffer boot console came up, the display (with its
    // keyboard input seam) is the only console — the UART then carries
    // the debug log alone, with no session that would draw over it; with
    // no display, the discovered UART is the only console. Each entry is
    // a `stream_write`/`stream_read` backing pair.
    .with_consoles(consoles)
    // Record the firmware-discovered installed-RAM total so the core mints
    // the `boot_facts_get` machine summary from it.
    .with_installed_memory(memory.installed_bytes)
    // Install the kernel seat registry (`plans/DISPLAY.md` D2 — input
    // follows the surface owner): its text sink is that same console's
    // keyboard queue, so an injected key press reaches the login by
    // default, and the window manager's owner-checked `display_acquire`
    // later routes whole records to the desktop keyboard channel instead.
    // Acquiring the seat also hands the console's display surface to the
    // session, and every way the lease can end gives it back (D8).
    .with_seat_registry(seat_registry)
    // Install the PID 1 spawn seam (`plans/PI.md` P6c-3): once every init
    // phase has succeeded and `kernel_main` emits `BootCompleted`, the core
    // invokes it to build `init`'s EL0 image and drop into user mode.
    .with_init(&crate::aarch64::init_spawn::AARCH64_INIT_SPAWN)
    // Install the runtime `spawn` producer + embedded-program registry
    // (`plans/SPAWN.md` SP3b): the `spawn` syscall resolves a path against
    // the registry and drives the producer to build a fresh, isolated child
    // address space, so PID 1 `init` can launch the user's session.
    .with_spawn(
        &crate::spawn_layout::PROGRAM_REGISTRY,
        &crate::aarch64::spawn_producer::AARCH64_PROCESS_SPAWN,
    )
    // Install the on-disk application store (`plans/APPS.md` deliverable 8):
    // this port embeds no program rows, so every command app and service is
    // spawned from its verified `/System` store bundle. The storage bring-up
    // resolves the store's readiness latch on every outcome (mount installed
    // or given up), so a spawn racing the mount parks and always wakes.
    .with_app_store(&crate::app_store::APP_STORE)
    // Hand the syscall dispatch hook the shared set-once credential cell
    // (`plans/PI.md` P11 Chunk B-2): `users_db_read` reads it on every
    // call, and the in-kernel root-unlock kthread publishes the mounted
    // root volume's database into the *same* cell once the operator's
    // passphrase unlocks the encrypted root. Until that install the cell
    // fails every read closed, identical to the previous `NULL_USERS_DB`
    // default — so login refuses every attempt until a root is mounted, and the metal-confirmed boot is unaffected.
    .with_users_db(&crate::root_mount::LATE_USERS_DB)
    .with_users_admin(&crate::root_mount::LATE_USERS_ADMIN)
    // Serve the discovered hardware tree through the injected `hw_tree`
    // source: the `hw_tree_read` / `hw_tree_wait` syscalls read the one
    // authoritative `HW_TREE` the boot path seeds and the floor bus bring-up
    // appends to (production installs `HW_TREE_SOURCE`), so the user-space
    // device manager observes the same inventory the kernel discovered
    // (Design D).
    .with_hw_tree(hw_tree)
    // Serve the `fs_*` syscalls through the production filesystem service
    // (`PREREQUISITES.md` P-A): it routes each operation through the secured
    // VFS against the late-installed read-only `/System` mount and resolves
    // caller groups against the late-installed identity table. Both cells
    // fail closed (`NotImplemented`) until the disk-owning task publishes the
    // `/System` window (`crate::system_mount::install_system_mount`) and the
    // encrypted-root unlock publishes the identity table, so wiring the hook
    // here changes no boot behaviour until those installs land.
    .with_filesystem(&crate::system_mount::FS_SERVICE)
    // Resolve `id::<volume-id>/…` paths against the volume forest the
    // mount/unlock tasks publish each mounted volume's stable identity
    // into (`plans/DEVICES.md` D3a). Until a volume is published every
    // `id::` path fails closed `NotFound`, so wiring the hook here changes
    // no boot behaviour until those installs land.
    .with_volumes(&crate::system_mount::VOLUME_FOREST)
    // Delegate runtime volume attach/detach (`plans/DEVICES.md` D3b) to
    // the production service; it fails closed `NotImplemented` until the
    // mount task wires its audit sink and pressure gauge, so this changes
    // no boot behaviour until that install lands.
    .with_volume_service(&crate::volume_service::VOLUME_SERVICE)
    // Resolve a spawn-as-user switch (`PREREQUISITES.md` P-C) against the
    // same set-once identity cell the filesystem service resolves caller
    // groups against and the root-unlock kthread publishes the on-disk
    // accounts into. Until that install a switch fails closed; the default
    // `spawn` (inherit) never consults it, so wiring the hook here changes no
    // boot behaviour until the unlock lands.
    .with_spawn_identity(&crate::root_mount::LATE_IDENTITY);
    if boot_info.validate().is_err() {
        halt_current_cpu()
    }
    kernel_main(boot_info)
}

/// What the pre-MMU boot phase resolved from the firmware device tree:
/// the MMIO facts the identity map's Device gigapage mask is derived
/// from ([`identity_device_mask`]).
struct EarlyDiscovered {
    /// A recognised console UART was found and the console base/model set.
    console: bool,
    /// A GICv2-class interrupt controller was found and its GICD/GICC
    /// bases set.
    gic: bool,
    /// The framebuffer boot console came up: a firmware mailbox was
    /// found, a display is attached, and the scan-out surface was
    /// allocated — console output now defaults to the screen, with the
    /// UART as the fallback (`plans/PI.md` P7b).
    video: Option<video::DiscoveredVideo>,
    /// Total byte length of the firmware device-tree blob (`totalsize`),
    /// `0` when no readable tree was found — the blob's RAM extent must
    /// stay in the identity map for the post-MMU walks.
    dtb_len: u64,
    /// The BCM2711 PCIe root-complex windows, when the tree describes a
    /// `brcm,bcm2711-pcie` bridge (`plans/PI.md` P10): the controller
    /// register block and outbound MMIO window must be folded into the
    /// identity Device mask, and the bring-up consumes all three windows.
    /// `None` on a board with no bridge (the QEMU `virt` shape).
    pcie: Option<platform::PcieDiscovery>,
}

/// Point the console and the GICv2 driver at the bases the firmware tree
/// describes and bring up the framebuffer boot console, before the MMU
/// is enabled.
///
/// All three discoveries are early-returning, `ranges`-aware walks
/// ([`console::configure_from_fdt`] / [`gic::configure_from_fdt`] /
/// [`video::configure_from_fdt`] over
/// [`tairix_fdt::scan_translated`]), so they are safe with
/// the MMU off — and the video bring-up *requires* this phase: with the
/// data caches off the CPU↔firmware mailbox exchange is coherent without
/// cache maintenance, and its state cell needs the single-threaded boot
/// CPU. A null pointer, an unreadable/invalid blob, or a tree missing a
/// fact leaves the corresponding pre-discovery default untouched — for
/// video, the UART console (fail closed).
fn configure_mmio_from_dtb(dtb: u64) -> EarlyDiscovered {
    let mut out = EarlyDiscovered {
        console: false,
        gic: false,
        video: None,
        dtb_len: 0,
        pcie: None,
    };
    if dtb == 0 {
        return out;
    }
    // SAFETY: on the boot hand-off `dtb` is the firmware/loader device-tree
    // pointer (`boot.s` preserves x0). `Fdt::from_ptr` validates the magic
    // and bounds the blob by its own `totalsize` before any further read,
    // and every read is a single byte, so the access is valid MMU-off. A
    // bogus pointer fails the magic check and returns `Err` rather than
    // faulting on structured data.
    let Ok(fdt) = (unsafe { Fdt::from_ptr(dtb as *const u8) }) else {
        return out;
    };
    out.dtb_len = fdt.total_size() as u64;
    out.console = console::configure_from_fdt(&fdt).is_some();
    // Bring the discovered console's line up before the first log byte:
    // on real Pi 4 silicon UART0 stays silent until GPIO 14/15 are muxed
    // to the PL011 and its line registers are programmed — QEMU's
    // powered-up PL011 masks the omission (`uart_init`).
    uart_init::init_from_fdt(&fdt);
    out.gic = gic::configure_from_fdt(&fdt).is_some();
    out.video = video::configure_from_fdt(&fdt);
    // Discover the BCM2711 PCIe bridge's windows for the in-kernel
    // USB-keyboard service (`plans/PI.md` P10). The early-returning
    // `scan_translated` walk is MMU-off-safe (it reads only the matched
    // node's own properties), exactly like the console/GIC/video walks
    // above; the QEMU `virt` tree carries no such node, so this is `None`
    // there and the keyboard service is never started.
    out.pcie = platform::pcie_bringup(&fdt);
    out
}

/// What the post-MMU boot phase resolved from the firmware device tree.
struct Discovered {
    /// Every `/memory` window `(base, size)` discovered from the firmware
    /// tree, in tree order — the RAM extents the `BootMemoryMap`
    /// (`plans/PI.md` P6c-1) reserves the kernel image out of and hands
    /// the allocator. A machine like the Pi 4 (8 GiB) declares several
    /// (below the MMIO hole, 1 GiB..4 GiB, and above 4 GiB); reading only
    /// the first under-reported an 8 GiB board as ~1 GiB. Empty when the
    /// tree declares none (fail closed — no memory map is built).
    ram_windows: Vec<(u64, u64)>,
    /// The generic-timer counter frequency (Hz) to seed the handle and
    /// the P4 live timer with: the `/timer` `clock-frequency` override
    /// when the tree declares one, else the `CNTFRQ_EL0` register value.
    timer_hz: u64,
    /// `true` when `timer_hz` came from the device-tree override rather
    /// than the `CNTFRQ_EL0` register.
    timer_hz_from_tree: bool,
    /// The PSCI conduit (`hvc`/`smc`) the `/psci` node declares, used to
    /// issue `CPU_ON` for SMP bring-up (`plans/PI.md` P5). `None` when the
    /// tree declares no PSCI node; bring-up then rides the spin-table
    /// release when the cpu nodes declare one, else fails closed.
    psci_method: Option<fdt::PsciMethod>,
    /// Every `/cpus/cpu@*` `reg` affinity (`MPIDR_EL1` `Aff0`–`Aff2`)
    /// the firmware tree declares, in tree order — the CPU inventory
    /// [`crate::cpu_topology::order_cpus`] validates into the dense map
    /// every per-CPU structure is sized from. Empty when the tree
    /// declares none or the walk fails (the boot then falls back closed
    /// to a single-CPU map).
    cpu_mpidrs: Vec<u64>,
    /// `(affinity, cpu-release-addr)` for every cpu node that declares
    /// the `spin-table` enable method (the Pi 4's stock firmware), in
    /// tree order — aligned to the dense map by
    /// [`crate::cpu_topology::align_release_addrs`] and used for
    /// bring-up only when the tree declares no PSCI node. Empty when
    /// none are declared or the walk fails (fail closed).
    cpu_spin_releases: Vec<(u64, u64)>,
}

/// Discover the board's post-MMU facts from the device tree at `dtb`:
/// the `/memory` window, the timer rate, and the PSCI conduit. (The
/// console and GIC bases are configured MMU-off by
/// [`configure_mmio_from_dtb`], before the identity map is built.)
///
/// A null pointer, an unreadable/invalid blob, or a tree missing a fact
/// leaves the corresponding pre-discovery `virt` default untouched (fail
/// closed).
fn configure_from_dtb(dtb: u64) -> Discovered {
    let mut out = Discovered {
        ram_windows: Vec::new(),
        // With no usable tree the register is the only counter-rate
        // source; P4's tree override (if any) overwrites this below.
        timer_hz: read_cntfrq(),
        timer_hz_from_tree: false,
        psci_method: None,
        cpu_mpidrs: Vec::new(),
        cpu_spin_releases: Vec::new(),
    };
    if dtb == 0 {
        return out;
    }
    // SAFETY: on the boot hand-off `dtb` is the firmware/loader device-tree
    // pointer (`boot.s` preserves x0). `Fdt::from_ptr` validates the magic
    // and bounds the blob by its own `totalsize` before any further read,
    // and every read is a single byte. The full-tree walks below run with
    // the MMU on (the caller enables it first). A bogus pointer fails the
    // magic check and returns `Err` rather than faulting on structured
    // data.
    let Ok(fdt) = (unsafe { Fdt::from_ptr(dtb as *const u8) }) else {
        return out;
    };
    // Collect every declared RAM range (every `reg` pair of every
    // `/memory` node), skipping zero-length entries. A malformed tree
    // discards the partial collection: the boot path then builds no
    // memory map at all rather than trusting a truncated inventory,
    // exactly as the former single-window read failed closed to `None`.
    let mut windows = Vec::new();
    if fdt
        .each_memory_region(|base, size| {
            if size != 0 {
                windows.push((base, size));
            }
        })
        .is_err()
    {
        windows.clear();
    }
    out.ram_windows = windows;
    // P4: prefer the board's `/timer` `clock-frequency` over the
    // `CNTFRQ_EL0` register, so the Pi 4's 54 MHz crystal is honoured
    // when the firmware tree declares it (no
    // `cfg(board)` fork).
    out.timer_hz_from_tree = fdt::timer_clock_frequency(&fdt).is_some_and(|hz| hz != 0);
    out.timer_hz = timer_frequency_hz(&fdt);
    // P5: discover the PSCI conduit (`hvc`/`smc`) the firmware tree
    // declares, so secondary-core bring-up issues `CPU_ON` over the
    // board's conduit rather than an assumed one.
    out.psci_method = fdt::psci_method(&fdt);
    // Collect every `/cpus/cpu@*` affinity so the bring-up starts the
    // cores the board *declares* (the Pi 4's four Cortex-A72s), never an
    // assumed count — along with each node's spin-table release word,
    // the PSCI-less start channel. A malformed walk discards the
    // partial lists — the boot then sizes for the one running core
    // rather than trusting a truncated inventory (fail closed).
    let mut cpus = Vec::new();
    let mut spin_releases = Vec::new();
    if fdt
        .each_cpu(|cpu| {
            let affinity = cpu.reg & smp::MPIDR_AFFINITY_MASK;
            cpus.push(affinity);
            if let Some(addr) = cpu.spin_table_release {
                spin_releases.push((affinity, addr));
            }
        })
        .is_err()
    {
        cpus.clear();
        spin_releases.clear();
    }
    out.cpu_mpidrs = cpus;
    out.cpu_spin_releases = spin_releases;
    // Record the console UART's receive-interrupt line so the root-unlock
    // console handoff can switch `login`'s input from polled to
    // interrupt-driven (`crate::aarch64::gic_irq::enable_uart_console_irq`).
    // Done here (post-MMU) rather than beside the MMU-off console-base
    // discovery because storing it flips an atomic `OnceCell`, which is only
    // sound with the MMU on; and unconditionally, so the no-disk path (which
    // never runs the unlock kthread) still gets it. A tree without a
    // representable console interrupt leaves `login` on the polled path (fail
    // closed — `login` then keeps re-polling, never errors).
    if let Some(intid) = crate::aarch64::root_unlock::console_spi(&fdt) {
        crate::aarch64::gic_irq::set_uart_console_intid(intid);
    }
    // Configure the BCM2711 root-complex MSI controller the `msi_alloc`
    // syscall drives: point it at the discovered RC register base and record
    // the shared GIC SPI its internal MSI controller raises (the
    // `brcm,bcm2711-pcie` node's second `interrupts` entry). A tree with no
    // such node leaves the controller unconfigured and `msi_alloc` fails
    // closed (the QEMU `virt` shape). Done post-MMU because both the
    // register-base store and the SPI `OnceCell` need the MMU on, exactly
    // like the console-interrupt record above.
    #[cfg(all(freestanding, kernel_isa = "aarch64"))]
    if let (Some(pcie), Some(msi_intid)) = (
        platform::pcie_bringup(&fdt),
        crate::aarch64::root_unlock::pcie_msi_spi(&fdt),
    ) {
        if let Ok(base) = usize::try_from(pcie.regs_phys) {
            tairix_arch_aarch64::brcm_msi::configure(base, pcie.inbound_size);
            crate::aarch64::gic_irq::set_brcm_msi_spi(msi_intid);
        }
    }
    out
}
